// بيانات منهج «اُكْتُبْ» — **المصدر الوحيد للحقيقة**، ونظيرُ `curriculum.js` في اقرأ.
//
// **وهو الملفُّ الوحيد في `app/js/` الذي لم يُنسخ من بذرة اقرأ** (`FAMILY.md §٥`
// تنصّ: «لا يُنسخ `curriculum.js` وكلُّ بياناتِ ومحتوى وشاشات المادة»). فما هنا
// اليومَ **هيكلٌ فارغٌ يُعلن الشكل ولا يحمل مادة** — والجلسة ٠ لا تكتب منهجاً.
//
// **ومن يملؤه؟** الجلسة ٣: أداةُ اشتقاقٍ في `tools/` تقرأ بيانات اقرأ (مجموعاته
// السبع وحروفَها وبنكَ كلماته وسلّمَ جمله) وتكتب هذا الملف — **آلياً لا بيد**
// (`SESSIONS.md`: «بيانات المنهج … تُشتقّ من بيانات اقرأ آلياً لا تُنسخ بيد»).
// ومسارات الحروف المرجعية تؤلّفها الجلسةُ ٢ بـ`tools/make_paths.html`.
//
// **ولماذا يُكتب فارغاً ولا يُترك غائباً؟** لأن العهدَ «خريطةٌ فارغة تفتح بلا
// أخطاء»: الوحداتُ المنسوخة كلُّها تقرأ من هنا، فالغيابُ يُسقِط التطبيق عند أول
// استيراد، والفراغُ المُعلَن يُشغّله ويُبقي الحرّاس خضراً على تطبيقٍ فارغ.

/**
 * **المحطات** — مراحلُ `METHOD.md §٤` الأربعَ عشرةَ وما تحتها من عقد.
 *
 * الشكل: `{ id, kind, title, face, sub, nodes: [{ part, … }] }`
 *   · `kind` — نوعُ المحطة، وهو مفتاحُ الشاشة التي تفتحها ومفتاحُ إعفائها أو
 *     قياسِها في `tools/test_measure.mjs`. أنواعُ اكتب المعلَنة في `METHOD.md §٤`:
 *     `warmup` (التهيئة الحركية) · `letter` (الحرف المعزول) · `form` (أشكال
 *     المواقع) · `join` (الوصل والنسخ) · `fade` (خفوت النموذج والإملاء) ·
 *     `sentence` (الجمل) · `gate` (البوابات الثلاث).
 *   · `nodes` — عقدُ المحطة بترتيبها؛ لكلٍّ `part` يُبنى منه معرّفُها.
 *
 * **وعددُها يُحسب لا يُكتب** (`METHOD.md §٤`: «~٦٥ محطة تُحسب من بيانات اقرأ
 * آلياً»): لا رقمَ في هذا الملف ولا في حارسٍ يقرؤه — الطولُ ثمرةُ البيانات.
 */
export const STAGES = [];

/**
 * **البوابات الثلاث** (`METHOD.md §٤`): `{ id, title, face, hint, before }`.
 *
 * و`before` معرّفُ المحطة التي تقف البوابةُ قبلها، أو `'end'` لبوابة الختام —
 * فالبوابةُ **بيانٌ مُعلَن**: إن سقطت من هنا سقطت من الرحلة ولا يبقى لها أثرٌ في
 * القفل (عينُ عقد `GATES` في اقرأ).
 */
export const GATES = [];

/** بوابةٌ بمعرّفها. */
export const gateById = (id) => GATES.find((gate) => gate.id === id) || null;

/** البوابةُ التي تقف قبل هذه المحطة (أو قبل ختام الرحلة: `'end'`). */
export const gateBefore = (where) => GATES.find((gate) => gate.before === where) || null;

/** محطةٌ بمعرّفها. */
export const stageById = (id) => STAGES.find((stage) => stage.id === id) || null;

/**
 * **المساراتُ المرجعية** لكل حرفٍ بأشكاله (`METHOD.md §٣.١`): شبكةٌ معيارية
 * `١٠٠٠×١٠٠٠`، والشكل:
 *
 *     PATHS['ب'].isolated = {
 *       strokes: [{ points: [[x, y], …], start: [x, y] }],
 *       dots: [{ at: [x, y], count: 1, after: true }],
 *     }
 *
 * **والنقاطُ بعد الجسم** (قاعدةُ الخطّ المدرسيّ، تُعلَن في صفحة الأسس).
 * تؤلّفها الجلسةُ ٢ بـ`tools/make_paths.html` — **لا تُكتب إحداثياتٌ بيد** —
 * ويفحصها `tools/check_paths.py`: لا حرفَ يدخل المنهج بلا مسارٍ عابرٍ للفحص.
 */
export const PATHS = {};

/** أشكالُ الموقع الأربعة — أسماؤها ثابتة لأنها تدخل مفاتيحَ ليتنر (`METHOD.md §٦`). */
export const FORMS = {
  ISOLATED: 'isolated',
  INITIAL: 'initial',
  MEDIAL: 'medial',
  FINAL: 'final',
};

/** اسمُ شكل الموقع كما يُقرأ في اللوحة والعناوين. */
export const FORM_NAMES = {
  [FORMS.ISOLATED]: 'معزول',
  [FORMS.INITIAL]: 'ابتدائي',
  [FORMS.MEDIAL]: 'وسطي',
  [FORMS.FINAL]: 'نهائي',
};

/** مسارُ حرفٍ بشكلِ موضعٍ بعينه — `null` إن لم يُؤلَّف بعد. */
export const pathOf = (letter, form = FORMS.ISOLATED) => PATHS[letter]?.[form] || null;
