/**
 * **صندوقُ المادّة — مربّعٌ للحرف والكلمة، وسطرٌ عريضٌ للجملة** (حكمُ المدير، ١٣
 * أغسطس ٢٠٢٦): «كلُّ شكلٍ يملأ صندوقَه» (قرارُ الجلسة ٢) يسري على الجملة كما سرى
 * على الحرف — **وصندوقُ السطر سطر**، فلا يُحشَر في مربّعٍ يخنق مقياسَ حروفه.
 * والمسافاتُ في المحرّك **مطلقةٌ على الشبكة كما هي**، وإنما يتّسع الصندوقُ فتكبر
 * المادّةُ فيه. ومَن لا صندوقَ في مساره فشبكتُه `١٠٠٠×١٠٠٠` كما كانت.
 */
export const boxOf = (ref) => {
  const box = ref?.box;
  return Array.isArray(box) && box.length === 2 && box[0] > 0 && box[1] > 0
    ? [box[0], box[1]] : [GRID, GRID];
};

/**
 * ————— **الحكمُ الثاني: «الشكلُ لا الأثر» في الخطوة الحرّة** (`METHOD.md §٥ب`) —————
 *
 * 🔴 **بلاغُ الميدان ٢ (المالك وطفلة، ١٣ أغسطس ٢٠٢٦)**: كتبت الطفلةُ **نوناً صحيحة**
 * في «اكْتُبْهُ وَحْدَكْ» — بدأت من دائرة البداية، ودارت دورتَها، وأغلقت كأسَها —
 * **فرُدّت**، لأنّ كأسها أضيقُ من كأس النموذج الخفيّ بأكثر من سماحة الانحراف.
 * **والشاهدُ الأثقل: تركت الجهاز.**
 *
 * **والحكمُ** (مالكٌ ومدير): في الخطوة الحرّة **وفيها وحدَها** يسقط الانطباقُ على
 * **موضع** المسار ويبقى الحكمُ على **الحركة** — يُقاس صندوقُ حبر الطفل، ويُوفَّق
 * النموذجُ عليه **إزاحةً وتحجيماً منتظماً** (لا تشويهَ نِسَب)، ثم تُطبَّق الشروطُ
 * الأربعةُ نفسُها على الموفَّق **بسماحةٍ كريمة**. فالمقيسُ تشابهُ الشكل والحجمُ
 * المعقول، لا مطابقةُ الخطّ الأول.
 *
 * **والخطوتان ٢ و٣ (الموجَّهةُ والخافتة) لا تُمَسّان**: النموذجُ فيهما مرئيّ
 * والتتبّعُ هو المقصود، فالانطباقُ فيهما على موضعه. **ولا يناقض هذا ق١**: ق١ اختار
 * تتبّعَ المسار ليقيس **البداية والاتجاه والترتيب** لا ليقيس الإحداثيات.
 *
 * **وتوفيقُ النموذج على الحبر وتوفيقُ الحبر على النموذج تشابهٌ واحد** — والتنفيذُ
 * هنا على **الحبر** (`toModel`) لأنّ بيانات المسار (طيّاتُه ونقاطُه ومقياسُه) تبقى
 * في إطارها فلا يُعاد بناؤها، **والسماحةُ تُقاس بمقياس المادّة الموفَّقة**: تُترك في
 * إطار النموذج فتصير نسبةً واحدةً من الحرف مهما كتبه الطفلُ كبيراً أو صغيراً. ولو
 * تُركت مطلقةً على الشبكة لَكانت الكتابةُ الصغيرة مسيَّبةً والكبيرةُ مضيَّقة.
 */
export const FREE = {
  /**
   * **كرمُ السماحة**: عاملٌ على سماحة المحطة كلِّها في الحكم الثاني — فالتوفيقُ
   * المنتظم يترك بقيّةً لا يبتلعها (كأسٌ أضيقُ نسبةً لا حجماً)، وهي المرادةُ
   * بـ«السماحة الكريمة». **ومُعايَرٌ بحالات الميدان المجمَّدة**: نونُ البلاغ بأوجهها
   * الأربعة تُقبَل، **والمعكوسةُ تُرَدّ ولو ضوعف الكرمُ ثلاثاً** — فما رُدّ فيه
   * الاتجاهُ لا تفتحه سماحة.
   */
  ease: 1.6,
  /**
   * **تعثّراتٌ متتالية يُفتَح بعدها المخرجُ الكريم** — ثلاثٌ: مرّةٌ حادثة، ومرّتان
   * صدفة، وثلاثٌ حال. **ولا انسدادَ أبداً** (`METHOD.md §٥ب`): «إعادةٌ بلا حدّ»
   * ليست عهداً بأن يبقى الطفلُ محبوساً — والطفلُ يخرج من الشاشة بيده لا بيأسه.
   */
  stumbles: 3,
};

/** **حجمٌ معقولٌ يُرشَد إليه بجملته** — لا يُردّ صامتاً (`METHOD.md §٥ب`). */
export const SIZE = { SMALL: 'size-small', BIG: 'size-big' };

/** وجملتاه — سطرا شاشةٍ تُقرآن كما تُقرأ `FAULT_TEXT`، ولا منطوقَ في هذا الملفّ. */
export const SIZE_TEXT = {
  [SIZE.SMALL]: 'اكْتُبْهُ أَكْبَرْ',
  [SIZE.BIG]: 'اكْتُبْهُ أَصْغَرْ',
};

/** أضيقُ مستطيلٍ يسع نقاطَ ضرباتٍ — صندوقُ حبرٍ أو صندوقُ نموذج. */
export function inkBox(strokes) {
  let x0 = Infinity; let y0 = Infinity; let x1 = -Infinity; let y1 = -Infinity;
  for (const stroke of strokes || []) {
    for (const p of stroke || []) {
      if (p[0] < x0) x0 = p[0];
      if (p[0] > x1) x1 = p[0];
      if (p[1] < y0) y0 = p[1];
      if (p[1] > y1) y1 = p[1];
    }
  }
  return x1 >= x0 ? {
    x0, y0, x1, y1, w: x1 - x0, h: y1 - y0, cx: (x0 + x1) / 2, cy: (y0 + y1) / 2,
  } : null;
}

/** نقاطُ النموذج كلُّها — **أجزاءَ المحرّك نفسَها** (أجساماً ونقاطاً)، فلا صورتان لشكل. */
export const refPoints = (ref) => partsOf(ref)
  .flatMap((part) => (part.kind === 'stroke' ? part.poly.pts : [part.at]));

/**
 * **التوفيق**: إزاحةٌ تُطابق مركزَي الصندوقين، وتحجيمٌ **منتظم** واحد للمحورين.
 *
 * **والمقياسُ وسطٌ هندسيّ لنسبتَي الضلعين** — فلا ينحاز إلى عرضٍ ولا إلى ارتفاع،
 * ونِسَبُ الشكل لا تُشوَّه: كأسٌ أضيقُ يبقى فيها فارقٌ يحتمله كرمُ السماحة، ولا
 * يُمطّ النموذجُ عليها فيصير كلُّ شكلٍ مقبولاً. **وضلعٌ أرقُّ من سماحة الانحراف لا
 * يحمل قياساً** (خطٌّ أفقيّ ارتفاعُه صفر)، فيُقرأ المقياسُ من أخيه وحدَه.
 */
export function fitFree(ref, strokes, tol = TOLERANCE) {
  const child = inkBox(strokes);
  const model = inkBox([refPoints(ref)]);
  if (!child || !model) return null;
  const rx = model.w > tol.lateral ? child.w / model.w : 0;
  const ry = model.h > tol.lateral ? child.h / model.h : 0;
  const s = rx && ry ? Math.sqrt(rx * ry) : (rx || ry || 1);
  return { s: s > 0 ? s : 1, child, model };
}

/** نقلُ نقطةٍ من إطار الطفل إلى إطار النموذج — عكسُ التوفيق، وهو هو. */
const toModel = (fit, p) => [
  fit.model.cx + (p[0] - fit.child.cx) / fit.s,
  fit.model.cy + (p[1] - fit.child.cy) / fit.s,
];

/**
 * **الحجمُ المعقول — وحدُّه محسوبٌ من الصندوق لا مكتوبٌ بيد**:
 *   · **أصغرُ ما يُقبَل** أن يزيد قطرُ حبره على **ممرّ السماحة** (`lateral × ٢`):
 *     شكلٌ يغرق في ممرّ سماحته لا يُقاس أصلاً — أيُّ خربشةٍ فيه تُقرأ حرفاً.
 *   · **وأكبرُ ما يُقبَل** أن يسعه **صندوقُ المادّة** وممرُّ سماحته من كلّ جهة.
 * وكلاهما جملةٌ تُقال («اكْتُبْهُ أَكْبَرْ») لا ردٌّ صامت.
 */
export function sizeOf(ref, strokes, tol = TOLERANCE) {
  const child = inkBox(strokes);
  if (!child) return null;
  const corridor = tol.lateral * 2;
  if (Math.hypot(child.w, child.h) < corridor) return SIZE.SMALL;
  const [bw, bh] = boxOf(ref);
  return child.w > bw + corridor || child.h > bh + corridor ? SIZE.BIG : null;
}

/** سماحةُ المحطة مكرَّمةً — الأبعادُ كلُّها بعاملٍ واحد، والتغطيةُ نسبةٌ فلا تُمَسّ. */
export const easeTolerance = (tol, factor = FREE.ease) => ({
  start: tol.start * factor,
  lateral: tol.lateral * factor,
  back: tol.back * factor,
  dot: tol.dot * factor,
  coverage: tol.coverage,
});

/**
 * **الحَكَمُ الثاني** — نظيرُ `judge` للخطوة الحرّة: يقيس الحجمَ أوّلاً (فيُرشِد إن
 * شذّ)، ثم يوفّق النموذجَ على صندوق الحبر، ثم **يستدعي الشروطَ الأربعة بأعيانها**
 * على الموفَّق. فلا حَكَمان ولا شرطٌ خامس: هو هو، والمتبدّلُ **إطارُ القياس**.
 */
export function judgeFree(ref, strokes, options = {}) {
  const tol = resolveTolerance(options.tolerance);
  const size = sizeOf(ref, strokes, tol);
  if (size) {
    return {
      done: false,
      accepted: false,
      size,
      attempts: strokes.length,
      parts: partsOf(ref).length,
      faults: [],
      codes: [],
      primary: null,
      metrics: { maxLateral: 0, maxBack: 0, coverage: 0, startDist: 0 },
    };
  }
  const fit = fitFree(ref, strokes, tol);
  const mapped = fit ? strokes.map((stroke) => stroke.map((p) => toModel(fit, p))) : strokes;
  const verdict = judge(ref, mapped, { ...options, tolerance: easeTolerance(tol) });
  return { ...verdict, size: null, scale: fit ? fit.s : 1 };
}

/**
 * **محاولةٌ حرّةٌ تُمشى لمسةً لمسة** — آلةُ الخطوة الحرّة كاملةً، **بلا شاشة**.
 *
 * **ولِمَ خارج اللوح؟** لأنّ العهدَ «لا تدريسَ بلا قياس» (`METHOD.md §٦`) يقع على
 * **الطريق لا على السطر**: أن تكون `score()` مكتوبةً في الشاشة لا يعني أنها تُنادى.
 * 🔴 وقد وقع ذلك بعينه (مراجعةُ المدير للجلسة م٣): محطةُ التمييز صارت **تدرّس ولا
 * تكتب مهارتها** لأنّ الطريقَ إلى `onDone` انقطع في الحكم الثاني — وحارسُ القياس
 * النصيّ أخضرُ لأنه يقرأ السطر. **فصارت الآلةُ تُدار في `node`** ويُقاس أنّ الطريق
 * يبلغ آخرَه (`tools/test_pen.mjs §٢ج` و`tools/test_measure.mjs`)، **واللوحُ يقودها
 * هو نفسُه** فلا مصدران: ما يُفحَص في العدّة هو ما يمشي تحت إصبع الطفل.
 *
 * **ويُحكَم كلَّما تمّت لمساتُ جزء** لا عند آخر جزءٍ وحدَه: فمَن كتب جسمَ النون يُقبَل
 * جسمُه ويثبت حبرُه، ثم تُقاس نقطتُه **موفَّقةً مع جسمه** — فيبقى موضعُ النقطة من
 * الجسم مقيساً (وهو من الشكل)، ولا يُترك الطفلُ بلا جوابٍ حتى يتمّ.
 *
 * @param {object} ref المسارُ المرجعيّ
 * @param {{tolerance?: number|object}} [options]
 */
export function createFreeRun(ref, options = {}) {
  const parts = partsOf(ref);
  /** كم لمسةً ينتظرها كلُّ جزء: الجسمُ واحدة، والنقطةُ بعددها. */
  const touchesOf = (part) => (part.kind === 'dot' ? part.count : 1);
  const reached = parts.reduce((run, part) => [...run, (run[run.length - 1] || 0) + touchesOf(part)], []);
  const whole = reached[reached.length - 1] || 0;
  /** النموذجُ إلى أوّل `k` جزءاً — فيُوفَّق ما كُتب على ما يقابله وحدَه لا على ما بعده. */
  const subsetRef = (k) => (k >= parts.length ? ref : {
    ...ref,
    strokes: (ref.strokes || []).slice(0, k),
    dots: (ref.dots || []).slice(0, Math.max(0, k - (ref.strokes || []).length)),
  });

  let touches = [];        // لمساتُ المحاولة الجارية — تُقرأ ولا تُخزَّن
  let settled = 0;         // كم جزءاً قبله الحكمُ الثاني
  let stumbles = 0;        // تعثّراتٌ متتالية — وبها يُفتَح المخرجُ الكريم

  const judgeAt = (count, ink) => judgeFree(count ? subsetRef(count) : ref, ink, options);

  return {
    parts,
    get settled() { return settled; },
    get stumbles() { return stumbles; },
    get done() { return settled >= parts.length; },
    reset() { touches = []; settled = 0; },
    /**
     * لمسةٌ رُفعت. تُعيد حكمَها، أو `null` إن كانت **في وسط جزءٍ بعددِ لمساته**
     * (نقطتان لتاءٍ مثلاً) فلا حكمَ بعدُ.
     */
    push(points) {
      touches.push(points);
      const covered = reached.indexOf(touches.length) + 1;
      if (!covered && touches.length < whole) return null;
      const verdict = judgeAt(covered, touches);
      if (verdict.accepted) {
        settled = covered;
        stumbles = 0;
        return { ok: true, restarted: false, size: null, text: null, verdict, done: this.done };
      }
      /**
       * **واستئنافُ الشكل من أوّله محاولةٌ جديدة لا خطأٌ في بقيّته** (🔴 مراجعةُ
       * المدير للجلسة م٣): مَن ثبت له جزءٌ ثم أعاد الشكلَ **كلَّه** — وهو أطبعُ ما
       * يفعله طفلٌ رُدَّ عليه — كانت ضربتُه الأولى تُقاس على **الجزء الباقي** فتُردّ
       * أبداً، فلا يبلغ آخرَه ولا تُكتب مهارتُه. (قِيست في محطة التمييز: يُكتب جسمُ
       * الأخت فيُقبَل — والجسمُ واحدٌ في ب ت ث ن ي — ثم لا يُقبَل بعده شيء.)
       *
       * **والفيصلُ أن تُسأل اللمسةُ وحدَها**: أتصلح **أوّلَ جزءٍ** من الشكل؟ فإن صلحت
       * فهي بدايةٌ جديدة، ويُطوى ما قبلها. ولا تُمنَح بلا استحقاق: تُحكَم بالشروط
       * الأربعة نفسِها كأيّ بداية.
       */
      if (settled > 0 && reached[0] === 1) {
        const fresh = judgeAt(1, [points]);
        if (fresh.accepted) {
          touches = [points];
          settled = 1;
          stumbles = 0;
          return { ok: true, restarted: true, size: null, text: null, verdict: fresh, done: this.done };
        }
      }
      stumbles++;
      touches.pop();
      return {
        ok: false,
        restarted: false,
        size: verdict.size,
        text: SIZE_TEXT[verdict.size] || null,
        verdict,
        done: false,
      };
    },
  };
}

/**
 * **شارةُ الشكل: المسارُ المرجعيّ مرسوماً ساكناً** — بلا لوحٍ ولا حَكَمٍ ولا حبرِ طفل.
 *
 * تحتاجها الشاشاتُ حيث يُذكَر شكلٌ ولا يُكتب: شريطُ حروف محطة الأشكال، وصفُّ
 * المتشابهات في محطة التمييز (الجلسة ٧). **وموضعُها هنا لا في الشاشة** لأنّ
 * «النموذجُ هو المقياس» (`METHOD.md §٣.٢`) قاعدةٌ على كلّ رسمٍ لشكلٍ لا على اللوح
 * وحدَه: ما يراه الطفلُ في الشارة هو عينُ ما يحكم به `createTrial` عليه بعد قليل —
 * ولا يُرسَم في هذا التطبيق حرفٌ من مصدرٍ آخر.
 *
 * **وأجزاؤها أجزاءُ المحرّك** (`partsOf`): الأجسامُ ثم النقاطُ بعددها كما يعرضها
 * اللوحُ نفسُه، فلا صورتان لشكلٍ واحد.
 */
/**
 * ————— مقاييسُ الإرشاد والعلامات: **تُشتقّ من المادّة لا تُكتب** —————
 *
 * 🔴 **بلاغُ عين المالك (١٣ أغسطس ٢٠٢٦)**: نقطةُ الحرف ونقطةُ البداية ورأسُ القلم
 * والسهمُ كانت أرقاماً ثابتة في شبكة الألف، سُنّت لحرفٍ **يملأ الشبكة**. وفي الكلمة
 * والجملة يصير الحرفُ جزءاً من حجمه **والنقطةُ لا تصغر** — فتطفو كُرَةً فوق الحرف
 * فيُقرأ «ف» واواً و«ة» هاءً. **وهو عيبُ صدقٍ لا زينة**: الطفلُ يقرأ نموذجَه خطأً.
 *
 * **والمقياسُ الآن مقياسُ حبر المادّة**: مؤلِّفُ خيال الكلمة يقيس **كم يبلغ حرفُ
 * المادّة من الحرف القانونيّ** (`fitTransform(...).s` في `tools/make_paths.html §٧ج`)
 * ويكتبه في المسار (`tolerance`) — وهو النسبةُ التي تُصغَّر بها الأشكالُ نفسُها،
 * فتصغر معها علاماتُها. **والحرفُ المفرد يملأ شبكتَه فنسبتُه واحد**.
 *
 * **والأرقامُ هنا نسبٌ إلى الحرف القانونيّ لا مقاساتُ شاشة**: تُضرَب في مقياس
 * المادّة فتخرج بوحدات مسارها. ويحرسها `tools/test_pen.mjs` **قياساً لا وصفاً**:
 * يقابل علامةَ حرفٍ مفردٍ بعلامة الحرف نفسِه في كلمة، فيلزم أن تصغر بنسبتها.
 */
export const GUIDE = {
  dot: 34,        // نقطةُ الحرف المرسومة في النموذج (نقاطُ ب ت ث …)
  start: 40,      // حلقةُ نقطة البداية الوامضة
  head: 26,       // رأسُ القلم الذي يسبق يدَ الطفل
  arrowTip: 46,   // طرفُ السهم أمام موضعه على المسار
  arrowBack: 12,  // وقاعدتُه خلفه
  arrowHalf: 26,  // ونصفُ عرضها
  arrowAt: 140,   // وأقصى ما يبعده السهمُ عن بداية الجزء
};

/**
 * **مقياسُ المادّة**: كم يبلغ حرفُها من الحرف القانونيّ — يكتبه مؤلِّفُ الخيال في
 * المسار نفسِه (`tolerance`)، فما لا مقياسَ له حرفٌ يملأ شبكتَه ونسبتُه واحد.
 */
export const scaleOf = (ref) => (typeof ref?.tolerance === 'number' && ref.tolerance > 0
  ? ref.tolerance : 1);

/** مقاييسُ الإرشاد لمادّةٍ بعينها — نسبُ `GUIDE` مضروبةً في مقياسها. */
export const guideOf = (ref) => {
  const s = scaleOf(ref);
  return Object.fromEntries(Object.entries(GUIDE).map(([k, v]) => [k, v * s]));
};

export function refGlyph(ref, className = 'ref-glyph') {
  const [bw, bh] = boxOf(ref);
  const g = guideOf(ref);
  const svg = sv('svg', {
    class: className, viewBox: `0 0 ${bw} ${bh}`, 'aria-hidden': 'true',
  });
  for (const part of partsOf(ref)) {
    if (part.kind === 'stroke') svg.append(sv('path', { class: 'ref-stroke', d: pathD(part.poly.pts) }));
    else svg.append(sv('circle', { class: 'ref-dot', cx: part.at[0], cy: part.at[1], r: g.dot }));
  }
  return svg;
}

/**
 * لوحُ الكتابة: عنصرٌ يُدرَج في الشاشة، فيه النموذجُ وحبرُ الطفل والحكم.
 *
 * @param {object} config
 * @param {object} config.ref المسارُ المرجعيّ (`METHOD.md §٣.١`)
 * @param {string} [config.mode] `guided` (المسار ظاهر) · `faint` (خافت) · `free` (صندوقٌ فارغ)
 * @param {number|object} [config.tolerance] سماحةُ المحطة
 * @param {boolean} [config.bounds] يرسم **ممرَّ السماحة** حول المسار (محطةُ التحكّم)
 * @param {number} [config.baseline] **سطرُ الكرّاسة** يُرسم تحت المادّة (محطةُ النسخ)
 * @param {number} [config.veil] **خفوتُ النموذج**: كم جزءاً من آخر الأجزاء يُخفى (محطةُ الخفوت)
 * @param {Function} [config.onFault] خطأٌ وقع — للقياس ولإرشاد الشاشة
 * @param {Function} [config.onPart] جزءٌ استُوفي
 * @param {Function} [config.onDone] اكتملت الأجزاء — ومعها حصيلةُ المحاولة
 * @param {Function} [config.onTry] **محاولةٌ حرّةٌ حُكم عليها** — ومعها جملةُ الحجم إن شذّ
 * @param {Function} [config.onStuck] **تعثّرٌ متكرر** — تفتح الشاشةُ به مخرجاً كريماً
 */
export function penSurface(config) {
  const {
    ref, mode = MODES.GUIDED, tolerance, bounds = false, baseline = null, veil = 0,
    onFault, onPart, onDone, onTry, onStuck, label = 'لوحُ الكتابة',
  } = config;

  const [bw, bh] = boxOf(ref);
  // **ومقاييسُ الإرشاد بمقياس المادّة** (بلاغُ عين المالك، ١٣ أغسطس): تُقرأ من
  // المسار نفسِه فتصغر النقطةُ والحلقةُ والسهمُ حيث يصغر الحرف — انظر `GUIDE` أعلاه.
  const g = guideOf(ref);
  const box = document.createElement('div');
  // **واللوحُ يتبع صندوقَ مادّته**: مربّعٌ للحرف والكلمة، **وسطرٌ للجملة** — يُعلَن
  // صنفاً ونسبةَ أبعادٍ معاً، فيرسم المتصفّحُ سطراً حيث المادّةُ سطر.
  box.className = `pen-box pen-box--${mode}${bw !== bh ? ' pen-box--line' : ''}`;
  if (bw !== bh) box.style.setProperty('--pen-ratio', String(bw / bh));
  const svg = sv('svg', {
    class: 'pen-surface', viewBox: `0 0 ${bw} ${bh}`, role: 'img', 'aria-label': label,
  });
  /**
   * **سطرُ الكرّاسة — من المادّة لا من زينة** (محطةُ النسخ، `METHOD.md §٤`: «الجلوسُ
   * على السطر»): موضعُه `ref.line` الذي خرج من **خيال الكلمة المُشكَّل** ساعةَ
   * التأليف، فالخطُّ الذي يراه الطفلُ تحت الكلمة هو الخطُّ الذي تجلس عليه حقّاً —
   * امتدادُ «النموذجُ هو المقياس» إلى السطر كما امتدّ إلى ممرّ السماحة.
   */
  const rule = sv('g', { class: 'pen-rule', 'aria-hidden': 'true' });
  const seat = baseline ?? ref?.line ?? null;
  if (seat != null) {
    rule.append(sv('line', { class: 'pen-baseline', x1: 0, y1: seat, x2: bw, y2: seat }));
  }
  const fence = sv('g', { class: 'pen-bounds' });      // ممرُّ السماحة (اختياريّ)
  const model = sv('g', { class: 'pen-model' });
  const trailed = sv('g', { class: 'pen-trail' });     // ما تلوّن تحت القلم
  const guide = sv('g', { class: 'pen-guide' });
  const inkLayer = sv('g', { class: 'pen-ink' });
  svg.append(rule, fence, model, trailed, guide, inkLayer);
  box.append(svg);

  /**
   * **خفوتُ النموذج — عرضٌ لا حكم** (`METHOD.md §٤` المرحلة ١٣): يُخفى من آخر
   * الأجزاء ما تقول به المحطةُ، فيبقى **مبدأُ الكلمة** مرئياً ويُستدعى ما بعده من
   * الذاكرة الحركية — والنقاطُ والعلاماتُ آخِرُ الأجزاء فتخفت أوّلاً.
   *
   * **والحَكَمُ لا يعلم بالخفوت**: الشروطُ الأربعة على المسار كاملاً كما هي — «النموذجُ
   * هو المقياس» (§٣.٢) قاعدةٌ على ما يُحكَم به، والخفوتُ حجابٌ على العين لا نقصٌ في
   * المادّة. فما يُطلَب من الطفل هو الكلمةُ نفسُها في كل درجة.
   */
  const hidden = Math.max(0, Math.min(veil, partsOf(ref).length));

  const trial = createTrial(ref, {
    tolerance,
    onFault: (fault) => { hint(fault.code); onFault?.(fault); },
    onProgress: ({ part, progress }) => paintProgress(part, progress),
  });
  const parts = trial.parts;

  /**
   * ————— **الخطوةُ الحرّة: حكمُها الثاني** (`METHOD.md §٥ب`) —————
   *
   * **ولِمَ يُؤجَّل الحكمُ إلى رفع القلم؟** لأنّ الموفَّقَ عليه — صندوقُ حبر الطفل —
   * لا يُعرَف قبل أن يُكتب. فالخطوةُ الحرّة تُحكَم **بالشكل تامّاً** لا لحظةً بلحظة،
   * وهو عينُ حكمها: «المهمُّ الشكلُ لا متابعةُ الخطّ المرسوم قبلاً». **والخطوتان
   * الموجَّهةُ والخافتة على حالهما**: النموذجُ فيهما مرئيّ فالحكمُ في لحظته كما كان.
   *
   * **وآلتُها في `createFreeRun` أعلاه** لا هنا: يقودها اللوحُ ويقودها الفاحصُ في
   * `node` بالسواء — فالطريقُ الذي يبلغ `onDone` **مقيسٌ** لا مدَّعىً (`METHOD.md §٦`).
   */
  const free = mode === MODES.FREE;
  const run = free ? createFreeRun(ref, { tolerance }) : null;

  // النموذجُ ورفيقُه المتلوّن: مسارٌ واحد يُرسم مرّتين — الثانيةُ مقصوصةٌ بالتقدّم،
  // وهو **مؤشّرُ التقدّم الحركيّ** (مخالفةُ اكتب المعلَنة لاقرأ، `METHOD.md §٥`).
  const modelPaths = [];
  const trailPaths = [];
  const veiled = (i) => i >= parts.length - hidden;
  for (const [order, part] of parts.entries()) {
    if (part.kind === 'stroke') {
      const d = pathD(part.poly.pts);
      /**
       * **ممرُّ السماحة — مرسومٌ بالسماحة نفسِها** (محطةُ «تحكّمٌ داخل حدود»،
       * `METHOD.md §٤`): عرضُه `٢ × سماحةِ الانحراف` التي يحكم بها `createTrial`
       * الآن، لا رقمَ زينةٍ يُختار. فالحدُّ الذي يراه الطفلُ هو الحدُّ الذي يُقاس به
       * — امتدادُ «النموذجُ هو المقياس» (`METHOD.md §٣.٢`) إلى السماحة.
       */
      if (bounds) fence.append(sv('path', { class: 'pen-fence', d, 'stroke-width': trial.tolerance.lateral * 2 }));
      const shape = sv('path', { class: 'pen-stroke', d });
      const trail = sv('path', {
        class: 'pen-stroke pen-stroke--trail',
        d,
        'stroke-dasharray': part.poly.len,
        'stroke-dashoffset': part.poly.len,
      });
      if (veiled(order)) { shape.classList.add('pen-veiled'); trail.classList.add('pen-veiled'); }
      model.append(shape);
      trailed.append(trail);
      modelPaths.push(shape);
      trailPaths.push(trail);
    } else {
      const mark = sv('circle', { class: 'pen-dot', cx: part.at[0], cy: part.at[1], r: g.dot });
      if (veiled(order)) mark.classList.add('pen-veiled');
      model.append(mark);
      modelPaths.push(mark);
      trailPaths.push(null);
    }
  }

  // نقطةُ البداية وسهمُ الاتجاه — وهما لسانُ الإرشاد كلُّه (`METHOD.md §٣.٤`)
  const startMark = sv('circle', { class: 'pen-start', r: g.start });
  const arrow = sv('path', { class: 'pen-arrow' });
  // **رأسُ القلم يُخفى بالصنف لا بسمة `hidden`**: أمسكته لقطةُ اللوح — السمةُ لا
  // تُخفي عنصرَ SVG على كل متصفّح، فظهرت نقطةٌ في زاوية اللوح عند (٠،٠). وإخفاؤه
  // في CSS مع سائر ما يُبدَّل بالخطوة أصدق: الحالُ في لوحٍ واحد لا في موضعين.
  const head = sv('circle', { class: 'pen-head', r: g.head, cx: 0, cy: 0 });
  guide.append(startMark, arrow, head);

  function paintGuide() {
    // **والمنتظَرُ في الخطوة الحرّة من حكمها الثاني** لا من الحَكَم اللحظيّ: هي
    // تُحكَم عند رفع القلم، فالجزءُ الذي تومض نقطتُه هو أوّلُ ما لم يستوفِه بعدُ.
    const part = free ? (parts[run.settled] || null) : trial.expected;
    // تمّت الأجزاء: يسقط الإرشادُ كلُّه — لا نقطةَ بدايةٍ لجزءٍ لم يبقَ (وبالصنف
    // لا بسمة `hidden`، للعلّة المكتوبة عند `head` أدناه).
    box.classList.toggle('pen-box--complete', !part);
    if (!part) return;
    startMark.setAttribute('cx', part.start[0]);
    startMark.setAttribute('cy', part.start[1]);
    if (part.kind !== 'stroke') { arrow.setAttribute('d', ''); return; }
    const { at, dir } = pointAt(part.poly, Math.min(part.poly.len * 0.16, g.arrowAt));
    const norm = Math.hypot(dir[0], dir[1]) || 1;
    const [ux, uy] = [dir[0] / norm, dir[1] / norm];
    const [px, py] = [-uy, ux];
    const tip = [at[0] + ux * g.arrowTip, at[1] + uy * g.arrowTip];
    arrow.setAttribute('d', `M${tip[0].toFixed(1)} ${tip[1].toFixed(1)}`
      + ` L${(at[0] - ux * g.arrowBack + px * g.arrowHalf).toFixed(1)} `
      + `${(at[1] - uy * g.arrowBack + py * g.arrowHalf).toFixed(1)}`
      + ` L${(at[0] - ux * g.arrowBack - px * g.arrowHalf).toFixed(1)} `
      + `${(at[1] - uy * g.arrowBack - py * g.arrowHalf).toFixed(1)} Z`);
  }

  function paintProgress(part, progress) {
    const trail = trailPaths[part];
    if (!trail) return;
    const len = parts[part].poly.len;
    trail.setAttribute('stroke-dashoffset', String(Math.max(0, len * (1 - Math.min(1, progress)))));
  }

  /**
   * الإرشادُ في لحظة الخطأ: وميضُ نقطة البداية وسهمُ الاتجاه — **ولا شاشةَ «خطأ»
   * ولا صوتَ عقاب ولا منعَ حبر**. والومضةُ تُعاد بإسقاط الصنف ثم إعادته.
   */
  function hint() {
    box.classList.remove('pen-box--hint');
    void box.offsetWidth;
    box.classList.add('pen-box--hint');
  }

  /** حبرُ المحاولة التي لم تُقبَل: **يخفت ويذهب** — لا يُمحى تحت اليد ولا يلتبس بالصواب. */
  function fadeInk(path) {
    if (!path) return;
    path.classList.add('pen-line--fade');
    setTimeout(() => path.remove(), 520);
  }

  /**
   * **حكمُ المحاولة الحرّة عند رفع القلم** — آلتُه `createFreeRun`، وهذه يدُها على
   * الشاشة: حبرٌ يثبت أو يخفت، وإرشادٌ يومض، وجملةُ حجمٍ تُقال، ومخرجٌ يُفتَح.
   *
   * **والمقبولُ يثبت حبرُه، والمردودُ يخفت وحدَه ويُعاد جزؤه** — ما ثبت لا يُطلَب
   * مرّتين، ولا تُمحى تحت يده كلمةٌ لأجل شولةٍ في آخرها. **ومَن أعاد الشكلَ من أوّله**
   * طُوي ما قبله وبدأت محاولتُه الجديدة (`restarted`).
   */
  function settleFree(drawn) {
    const result = run.push(inkPoints);
    if (!result) return;                       // في وسط جزءٍ بعددِ لمساته
    if (result.ok) {
      // **واستئنافُ الشكل يطوي ما قبله**: حبرُ المحاولة الماضية يخفت ويذهب، فلا
      // يبقى على اللوح شكلان.
      if (result.restarted) {
        for (const path of [...inkLayer.querySelectorAll('path')]) if (path !== drawn) fadeInk(path);
      }
      drawn?.classList.add('pen-line--kept');
      onTry?.(result);
      onPart?.({ ok: true, progress: 1 });
      paintGuide();
      if (result.done) onDone?.(result.verdict);
      return;
    }
    fadeInk(drawn);
    hint();
    // **الخطأُ الأوّل هو الخطأ** (`verdict()` أعلاه): يُرفَع وحدَه إلى القياس، فلا
    // تُحصى على محاولةٍ واحدة شكاوى يتلو بعضُها بعضاً.
    if (result.verdict.faults[0]) onFault?.(result.verdict.faults[0]);
    onTry?.(result);
    paintGuide();
    if (run.stumbles >= FREE.stumbles) onStuck?.(run.stumbles);
  }

  // ————— الالتقاط: Pointer Events، والإصبعُ والقلمُ سواء (ق٤) —————
  //
  // **وتجاهلُ لمس الكفّ**: مَن أمسك قلماً استقرّ كفُّه على الشاشة — فأولُ حدثِ قلمٍ
  // يُغلق باب اللمس في هذه الجلسة. ولا يُشترط جهازٌ بقلم: الإصبعُ هو الافتراض، ولا
  // يُحرَم طفلٌ جهازُه بلا قلم.
  //
  // **وحدُّه معلَنٌ** (ملاحظةُ مراجعة الجلسة ١، مقبولةٌ غيرَ حاجزة): `sawPen` **لا
  // يُصفَّر** ما دام اللوحُ قائماً — فطفلٌ كتب بالقلم ثم أراد الإصبعَ على اللوح
  // نفسِه يُهمَل لمسُه حتى يُعاد بناءُ اللوح. ومقبولٌ اليومَ لأن اللوح يُبنى لكل
  // تمرين، فتبديلُ الأداة يقع بين تمرينين لا في وسط حرف. ولو صار للطفل لوحٌ واحد
  // يعيش عبر تمارين (الجلسة ٥) فموضعُ العلاج هنا: تصفيرُه عند مهلةٍ بلا حدث قلم.
  let sawPen = false;
  let active = null;          // مؤشّرٌ واحدٌ يكتب — وما سواه لمسُ كفٍّ أو أصابعَ أخرى
  let rect = null;            // مقاسُ اللوح يُقرأ مرّةً عند النزول لا في كل حركة
  let queue = [];
  let frame = 0;
  let inkPath = null;
  let inkPoints = [];

  /** إحداثيُّ الإصبع على شبكة المادّة — **بصندوقها هي** لا بمربّعٍ مفترَض. */
  function toGrid(event) {
    const unit = Math.min(rect.width / bw, rect.height / bh) || 1;
    const ox = rect.left + (rect.width - bw * unit) / 2;
    const oy = rect.top + (rect.height - bh * unit) / 2;
    return [(event.clientX - ox) / unit, (event.clientY - oy) / unit];
  }

  /** الرسمُ والحكمُ في `requestAnimationFrame` — لا في كل حدثِ حركة (`METHOD.md §٣.٦`). */
  function pump() {
    frame = 0;
    const batch = queue;
    queue = [];
    for (const p of batch) {
      if (dist(inkPoints[inkPoints.length - 1], p) < MIN_STEP) continue;
      inkPoints.push(p);
      // **والخطوةُ الحرّة لا تُحكَم لحظةً بلحظة** (`settleFree`): حبرُها يُجمَع ثم
      // يُوفَّق النموذجُ عليه عند الرفع — فالحَكَمُ اللحظيّ لا يُطعَم فيها شيئاً.
      if (!free) trial.move(p[0], p[1]);
    }
    if (inkPath) inkPath.setAttribute('d', pathD(inkPoints));
  }

  function onDown(event) {
    if (active !== null) return;                          // إصبعٌ ثانٍ أثناء الكتابة
    if (event.pointerType === 'pen') sawPen = true;
    else if (event.pointerType === 'touch' && sawPen) return;   // كفٌّ على الشاشة والقلمُ يكتب
    active = event.pointerId;
    rect = svg.getBoundingClientRect();
    event.preventDefault();
    try { svg.setPointerCapture(event.pointerId); } catch { /* مؤشّرٌ لا يقبل الأسر */ }

    const p = toGrid(event);
    inkPoints = [p];
    inkPath = sv('path', { class: 'pen-line', d: pathD(inkPoints) });
    inkLayer.append(inkPath);
    if (!free) trial.down(p[0], p[1]);
    listen(true);
  }

  /** أحداثُ الحركة والرفع تُعلَّق ما دام إصبعٌ يكتب، وتُنزَع عند رفعه — فلا تبقى
      معلّقةً على النافذة بعد مغادرة الشاشة. */
  function listen(on) {
    const how = on ? window.addEventListener : window.removeEventListener;
    how.call(window, 'pointermove', onMove);
    how.call(window, 'pointerup', onUp);
    how.call(window, 'pointercancel', onUp);
  }

  function onMove(event) {
    if (event.pointerId !== active) return;
    // نقاطُ الحركة المضغوطة (`getCoalescedEvents`) تُلتقط كلُّها: على آيباد يصل
    // القلمُ بمعدّلٍ أعلى من معدّل الإطارات، وإسقاطُها يقطّع الحبر ويكذب على الحَكَم.
    const points = typeof event.getCoalescedEvents === 'function' ? event.getCoalescedEvents() : [event];
    for (const one of points.length ? points : [event]) queue.push(toGrid(one));
    if (!frame) frame = requestAnimationFrame(pump);
  }

  function onUp(event) {
    if (event.pointerId !== active) return;
    active = null;
    listen(false);
    if (frame) { cancelAnimationFrame(frame); pump(); }
    /**
     * **وموضعُ رفع القلم يُقرأ ولا يُطرَح** (الجلسة ٩، نظيرُ ما في `simplify`):
     * مرشِّحُ الخطوة الصغرى في `pump` يبلع آخرَ ما مشاه القلمُ إن كان دون ستّ وحدات
     * من آخر نقطةٍ محفوظة — **فيُقرأ للطفل تقدّمٌ أنقصُ ممّا مشى**. ولا يظهر على حرفٍ
     * يملأ صندوقَه، **ويقف بالطفل على ضربة العلامة في السطر**: شولةٌ طولُها بضعُ
     * وحداتٍ وثلاثون تُقرأ تغطيتُها دون العتبة فتُردّ كتابتُها الصحيحة قِصَراً، ثم
     * تُقاس ضربتُه التالية على جزءٍ لم يُستوفَ فتتوالى الشكاوى (`order`/`start-far`)
     * **فينسدّ الطريق**. وأمسكه فحصُ الرحلة عند «وَاسِعَةْ نَظِيفْ».
     *
     * **ولا عتبةَ جديدة**: نقطةُ الرفع موضعٌ حقيقيّ مشاه القلمُ، وحقُّها أن تُقرأ.
     */
    const end = toGrid(event);
    const tip = inkPoints[inkPoints.length - 1];
    if (tip && dist(tip, end) > 0) {
      inkPoints.push(end);
      if (!free) trial.move(end[0], end[1]);
      if (inkPath) inkPath.setAttribute('d', pathD(inkPoints));
    }
    // **الخطوةُ الحرّة تُحكَم هنا** بحكمها الثاني: الشكلُ تامّاً موفَّقاً على صندوق حبره.
    if (free) {
      const drawn = inkPath;
      inkPath = null;
      settleFree(drawn);
      return;
    }
    const result = trial.up();
    if (result?.ok) {
      onPart?.(result);
      paintProgress(trial.index - 1, 1);
      inkPath?.classList.add('pen-line--kept');
    } else {
      // المحاولةُ التي لم تستوفِ الجزء: حبرُها **يخفت ويذهب** — لا تُمحى تحت اليد
      // ولا تُترك فتلتبس بالصواب. ولا رسالةَ خطأ: الإرشادُ وحدَه (الشرطُ الرابع من §٣.٤).
      const gone = inkPath;
      gone?.classList.add('pen-line--fade');
      setTimeout(() => gone?.remove(), 520);
      if (trial.expected?.kind === 'stroke') paintProgress(trial.index, 0);
      hint();
    }
    inkPath = null;
    paintGuide();
    if (trial.done) onDone?.(trial.verdict());
  }

  // **النزولُ على اللوح، والحركةُ والرفعُ على النافذة** (`listen` أعلاه): طفلٌ يتجاوز
  // حافةَ اللوح بيده لا تنقطع كتابتُه — ولو عُلِّقت الأحداثُ على اللوح وحدَه لضاع
  // رفعُ الإصبع خارجه فبقيت المحاولةُ معلّقةً إلى الأبد. (وأسرُ المؤشّر يكفي حيث
  // يعمل، ولا يعمل في كل حال.)
  svg.addEventListener('pointerdown', onDown);

  // ————— العرضُ المتحرك: «شاهِد» (`METHOD.md §٥.١`) —————
  const SPEED = 900;          // وحدةَ شبكةٍ في الثانية — سرعةُ يدٍ تكتب لا تمرّ
  let playing = 0;

  /** يرسم النموذجَ حرفاً كما يُكتب: جزءاً جزءاً، من المسار المرجعيّ نفسِه. */
  function play() {
    stop();
    box.classList.add('pen-box--playing');
    for (const trail of trailPaths) if (trail) trail.setAttribute('stroke-dashoffset', trail.getAttribute('stroke-dasharray'));
    let part = 0;
    let started = 0;

    const step = (now) => {
      if (!started) started = now;
      const current = parts[part];
      if (!current) { stop(); return; }
      if (current.kind === 'dot') {
        modelPaths[part].classList.add('pen-dot--on');
        part++; started = 0;
        playing = requestAnimationFrame(step);
        return;
      }
      const elapsed = (now - started) / 1000;
      const walked = Math.min(current.poly.len, elapsed * SPEED);
      trailPaths[part].setAttribute('stroke-dashoffset', String(current.poly.len - walked));
      // ورأسُ القلم يغيب حيث غاب النموذج — وإلا كشف العرضُ ما أخفاه الخفوت
      head.classList.toggle('pen-veiled', veiled(part));
      const { at } = pointAt(current.poly, walked);
      head.setAttribute('cx', at[0]);
      head.setAttribute('cy', at[1]);
      if (walked >= current.poly.len) { part++; started = 0; }
      playing = requestAnimationFrame(step);
    };
    playing = requestAnimationFrame(step);
  }

  function stop() {
    if (playing) cancelAnimationFrame(playing);
    playing = 0;
    box.classList.remove('pen-box--playing');
  }

  function reset() {
    stop();
    trial.reset();
    // **والتعثّراتُ لا تُصفَّر بزرّ «أعِدْ»**: هي عدَدُ ما لقيه الطفلُ لا عددُ ما
    // ضغطه — فمن أعاد مرّتين وتعثّر يجد المخرجَ الكريم مفتوحاً كما يجده مَن لم يُعِد.
    run?.reset();
    inkLayer.replaceChildren();
    inkPoints = [];
    inkPath = null;
    for (const trail of trailPaths) if (trail) trail.setAttribute('stroke-dashoffset', trail.getAttribute('stroke-dasharray'));
    for (const shape of modelPaths) shape.classList.remove('pen-dot--on');
    paintGuide();
  }

  paintGuide();

  return {
    el: box,
    svg,
    trial,
    play,
    stop,
    reset,
    /**
     * **أثرُ الطفل كما رسمه** — عقدُ حبره المرسومة على هذا اللوح، تُقرأ ولا تُخزَّن.
     *
     * وموضعُها هنا لا في الشاشة: الشاشةُ لا تنقّب في بنية اللوح. وتستعملها ميداليةُ
     * الختام (حكمُ المالك في `REVIEW_IDENTITY.md §٣ج`) لتحمل **يدَ الطفل هو** لا
     * نموذجاً مرسوماً. **ولا يمسّ ذلك عهدَ الخصوصية**: الحبرُ يُنسَخ إلى عقدةٍ على
     * الشاشة نفسِها ويموت بها — لا مخزنَ ولا شبكةَ، وهذا الملفُّ لا يعرف الاثنين.
     */
    ink() {
      return [...inkLayer.querySelectorAll('path')].map((path) => path.getAttribute('d'));
    },
    /** مغادرةُ الشاشة: يُوقَف العرضُ ويُنزَع ما عُلِّق على النافذة من أحداث. */
    destroy() { stop(); listen(false); active = null; },
    /**
     * تبديلُ خطوة الحلقة بلا إعادة بناءٍ للوح (شاهِد ← موجَّه ← خافت ← حرّ).
     *
     * **وصنفُ السطر يبقى**: مادّةُ الجملة لوحُها سطرٌ لا مربّع (`pen-box--line` يُقرأ
     * من صندوق المادّة عند البناء)، فلو كُتب الصنفُ من أوّله لَانقلب لوحُ الجملة
     * مربّعاً أوّلَ تبديلٍ للوضع — والوضعُ يُبدَّل في البوابة بزرّ «شاهِدْ».
     */
    setMode(next) {
      box.className = `pen-box pen-box--${next}${bw !== bh ? ' pen-box--line' : ''}`;
    },
  };
}
