/**
 * **الطيّاتُ المعلَنة** بأطوالها على المسار (`METHOD.md §٣.١`).
 *
 * في العربية حروفٌ **يعود القلمُ فيها على أثره في حركةٍ واحدة**: سنُّ ب ت ث ن ي س ش،
 * وعمودُ اللام الوسطية، وتُوَيْجُ الباء النهائية. والمسارُ المرجعيّ يفكّ ضلعَيها
 * بعرض الحبر (`tools/make_paths.html`) فيتمايزان للعين، **لكنّ مكانهما في الحرف
 * واحد** — فالمكانُ الواحد يحمل طولين من المسار، وهو بعينه ما يفترضه الشرطُ الثاني
 * ألّا يقع (تقدّمٌ رتيبٌ على المسار يفترض أن الموضعَ يدلّ على الطول دلالةً واحدة).
 *
 * **فتُعلِن البياناتُ أين ينكسر هذا الافتراض** — أرقامُ نقاطٍ في `points` تُصدِرها
 * عدّةُ التأليف من مفرق الهيكل آلياً (`{ from, apex, to }`)، وتُقرأ هنا أطوالاً.
 * **وهي صفةُ المسار لا شرطٌ خامسٌ على الطفل**: ما لم يُعلَن فالعودُ فيه ارتدادٌ كما
 * كان، ويحرسها `tools/check_paths.py` بنيةً (ضلعان متقابلان، ولا طيّةَ على سويّة).
 */
function foldsOf(stroke, poly) {
  const last = poly.cum.length - 1;
  const whole = (v) => Number.isInteger(v) && v >= 0 && v <= last;
  return (stroke?.folds || [])
    .filter((f) => f && whole(f.from) && whole(f.apex) && whole(f.to)
      && f.from < f.apex && f.apex < f.to)
    .map((f) => {
      const from = poly.cum[f.from];
      const apex = poly.cum[f.apex];
      const to = poly.cum[f.to];
      /**
       * **والمرآةُ صفةُ الشوكة لا صفةُ كلِّ طيّة** (الجلسة ٨، بعد حكم المدير في
       * الانطباقات): الطيّةُ تقول «مكانٌ واحد بطولين»، ولها وجهان في الكلمة:
       *   · **شوكةٌ** يعود فيها القلمُ على أثره — فطرفاها موضعٌ واحد، والموضعُ على
       *     ضلعها الصاعد يقابل نظيرَه على النازل **مرآةً** (ارتفاعٌ بارتفاع).
       *   · **وانطباقٌ متوازٍ** يمشي فيه القلمُ حبرَ الوصل مرّتين في اتجاهٍ واحد
       *     بينهما نزهةٌ في حرفٍ آخر — فطرفاها متباعدان، **والمرآةُ فيه كذبٌ**:
       *     تتقهقر كلّما تقدّم القلم، فتُقرأ حركتُه ارتداداً وهي مصيبة (قِيس على
       *     «تمر»: القراءةُ المرآةُ تنزل ٥٠٦ ← ٤٩٢ ← ٤٧٨ والقلمُ يصعد ٥٢٩ ← ٥٥٣).
       * **وتُقرأ من الشكل لا تُعلَن**: طيّةٌ تعود من حيث بدأت (طرفاها أقربُ من أقصر
       * ضلعيها) شوكةٌ فلها مرآتُها، وما سواها يُقاس على ضلعه وحدَه.
       */
      // **والفيصلُ أن يُسأل الشكلُ نفسُه**: تُؤخذ نقطتان على الضلع الأول ويُنظر أين
      // تقعان من الثاني — فإن **تقهقر** نظيرُهما كلّما تقدّمتا فهي شوكةٌ لها مرآتُها،
      // وإن **تقدّم معهما** فهو انطباقٌ متوازٍ يُقاس كلُّ ضلعٍ فيه على نفسه.
      // **والقياسُ يُحبَس في الضلع النازل** (`within`)، **ويُؤخذ من أوثق العيّنات**:
      // الانطباقُ قد لا يعمّ الضلعَ كلَّه، فعيّنةٌ في موضعٍ لا نظيرَ له تكذب (قِيست
      // في «السَّمَكْ»: عيّنةُ السبعين بالمئة على بُعد ٥٢ ونظيرُها موهوم). فتُمسَح
      // تسعُ عيّنات، ويُحكَم بأقربها إلى الحبر: أيتقهقر نظيرُها كلّما تقدّمت؟
      const shots = [];
      for (let k = 1; k < 9; k++) {
        const t = k / 9;
        const at = pointAt(poly, from + (apex - from) * t).at;
        const hit = within(nearestOn(poly, at, apex, to), apex, to);
        shots.push({ t, len: hit.len, d: hit.d });
      }
      const solid = shots.sort((a, b) => a.d - b.d).slice(0, 3);
      let sign = 0;
      for (const a of solid) {
        for (const b of solid) if (a.t < b.t) sign += Math.sign(a.len - b.len);
      }
      return { from, apex, to, mirror: sign > 0 };
    })
    .sort((a, b) => a.to - b.to);
}

/** الطيّةُ التي لم تُقطَع بعد — وما وراءها لا شأنَ له بموضع القلم الآن. */
const foldAhead = (folds, reach) => folds.find((fold) => reach < fold.to) || null;

/**
 * **المرورُ الثاني في الاتجاه نفسِه** — الحالةُ الثالثةُ المعلَنة (`METHOD.md §٣.١`).
 *
 * الطيّةُ تقول «مكانٌ واحد بطولين **ذهاباً وإياباً**»، وهذه تقول «مكانٌ واحد بطولين
 * **مروراً ثم مروراً في الاتجاه عينه**» — يمشي القلمُ حبراً، ثم ينزهُ في جزءٍ من
 * الحرف، ثم يعود فيمشي ذلك الحبرَ بعينه في الجهة التي مشاه بها أوّلَ مرّة.
 *
 * **وسندُها برهانٌ لا ذوق** (مراجعةُ الإدارة لجلسة ص٢/و، ١٩ أغسطس ٢٠٢٦): حبرُ جسم
 * `ط` و`ظ` الموصولتين **أربعةُ أضلاع**، **وقدما الحلقة درجتُهما ٣ ورأسا الوصل ١** —
 * أربعةُ رؤوسٍ فرديّة **فلا مسارَ أويلريّ فيه**، **وأقلُّ إصلاحٍ تكرارُ السطر تحت
 * الحلقة بعينه**. ⇐ **فالازدواجُ صفةُ الخطّ لا صنعتُنا**، ومحرّكٌ لا يمثّله ناقصٌ
 * بنيوياً — يلقاه في كلِّ شكلٍ يجاوز حبرُه رأسين فرديّين.
 *
 * **وما تُصلحه**: المروران ينطبقان في المكان، **فالأقربُ إلى قلم الطفل قد يكون
 * الآخرَ لا الذي هو فيه** — ونافذةُ الإسقاط تحبس المقروءَ في مدىً حول مؤشّره فلا
 * تبلغه، **فتُلتمَس القراءةُ في ثالثٍ يصادف قربَه** (قِيس على `ط/وسطي`: قلمُ الطفل
 * على بُعد وحدةٍ من المرور الثاني وعلى ٢١ من مروره هو، فقُرئ على ضلع الحلقة الصاعد
 * على بُعد ١٥ — **فقفز التقدّمُ ثمانين ثم قُرئ رجوعُه إلى حبره `reverse`**).
 *
 * **فتُعلِن البياناتُ المكانَ الواحد بطوليه** — `{ from, to, again, until }` أرقامَ
 * نقاطٍ تُصدِرها عدّةُ التأليف بمقاييس هذا الملفّ بأعيانها
 * (`owner_layer.self_passes`) — ويحرسها `tools/check_paths.py` بنيةً.
 */
function passesOf(stroke, poly) {
  const last = poly.cum.length - 1;
  const whole = (v) => Number.isInteger(v) && v >= 0 && v <= last;
  return (stroke?.passes || [])
    .filter((s) => s && whole(s.from) && whole(s.to) && whole(s.again) && whole(s.until)
      && s.from < s.to && s.to <= s.again && s.again < s.until)
    .map((s) => ({
      from: poly.cum[s.from], to: poly.cum[s.to],
      again: poly.cum[s.again], until: poly.cum[s.until],
    }))
    .sort((a, b) => a.until - b.until);
}

/** المرورُ الذي لم يُقضَ بعد — وما وراءه لا شأنَ له بموضع القلم الآن. */
const passAhead = (passes, reach) => passes.find((pass) => reach < pass.until) || null;

/**
 * أجزاءُ الشكل بترتيب كتابتها: **الأجسامُ ثم النقاط** (`METHOD.md §٣.١`: النقاطُ
 * بعد الجسم — قاعدةُ الخطّ المدرسيّ، وتُعلَن في صفحة الأسس). والترتيبُ هنا هو عينُ
 * الشرط الرابع، ويحرس `check_paths.py` (الجلسة ٢) أن تأتي بيانات الحرف موافقةً له.
 */
export function partsOf(ref) {
  const parts = [];
  for (const stroke of ref?.strokes || []) {
    const poly = prepare(stroke.points);
    parts.push({
      kind: 'stroke',
      poly,
      folds: foldsOf(stroke, poly),
      passes: passesOf(stroke, poly),
      start: stroke.start || stroke.points[0],
      end: poly.pts[poly.pts.length - 1],
      // **وسماحتُه المعلَنة تسافر معه** (`ease`، انظر `partCoverage` أعلاه): تُقرأ من
      // البيان ولا تُستنبَط هنا — فما لم يُعلَن فسماحتُه سماحةُ المحطة كما كانت.
      ease: stroke.ease,
    });
  }
  for (const dot of ref?.dots || []) {
    parts.push({
      kind: 'dot', at: dot.at, count: dot.count || 1, start: dot.at, end: dot.at, ease: dot.ease,
    });
  }
  return parts;
}

const startDist = (part, p) => dist(part.start, p);

/**
 * **الشكلُ المغلق**: مسارٌ يعود طرفُه إلى **دائرة بدايته** — دائرةُ التهيئة، وحلقاتُ
 * م/ه/و. والمقياسُ من جنس الشرط الأول لا رقماً حرّاً: ما دام الطرفُ داخل الدائرة التي
 * يُقبَل فيها النزول فالموضعُ الواحد يحمل طولين (رأسَ المسار وذيلَه) — وهو بعينه ما
 * يجعل الطولَ في الشكل المغلق **دائرياً**: الرجوعُ خطوةً من البداية يقع في الطول
 * قفزةً إلى آخر المسار.
 */
const isClosed = (part, tol) => part.kind === 'stroke'
  && dist(part.poly.pts[0], part.end) <= tol.start;

/** فرقُ طولين على مسارٍ دائريّ: أقصرُ الطريقين بينهما، موجباً تقدّماً وسالباً رجوعاً. */
function cyclicGap(len, total) {
  if (!(total > 0)) return len;
  const wrapped = ((len % total) + total) % total;
  return wrapped > total / 2 ? wrapped - total : wrapped;
}

/**
 * **رأسُ المسار** — المدى الذي يُرسى فيه نزولُ الإصبع، لا المسارُ كلُّه.
 *
 * 🔴 **ثغرةُ ذيل الشكل المغلق** (كشفتها مراجعةُ المدير للجلسة ١، وأُصلحت قبل
 * الالتزام): كان الإرساءُ `nearestOn(poly, p, 0, poly.len)` — على المسار كلِّه.
 * والشكلُ المغلق (دائرةُ التهيئة، وحلقاتُ م/ه/و) يعود ذيلُه إلى جوار بدايته، فنزولٌ
 * **داخل دائرة البداية** لكنه أقربُ عرضياً إلى القطعة الخاتمة كان يُرسى على **ذيل**
 * المسار: فيصير `reach ≈ len` من اللحظة الأولى، وتبلغ التغطيةُ ٠٫٩٧ ويُقبَل الجزءُ
 * **بحركةٍ ذرّية بلا كتابة**. (أُعيد إنتاجها بدائرةٍ من ٧٢ قطعة تبدأ من قمتها ونزولٍ
 * عند ٥٦٠،٢٠٥ فستِّ نقاطٍ قصيرة: `accepted=true, coverage=0.97, codes=[]`.)
 *
 * **فالنزولُ يُرسى على رأس المسار وحدَه**: مَن نزل في موضعه الصحيح فموضعُه في رأسه
 * قطعاً، ومَن نزل في غيره فقد أخطأ الشرطَ الأول وقُيّد خطؤه — ولا يرث أحدٌ تقدّماً
 * لم يمشِه. والمدى **مقيَّدٌ بسماحة البداية نفسِها** لا بنسبةٍ حرّة، فهو من جنس
 * الشرط الأول: دائرةُ البداية مضروبةً في اثنين، وعُشرُ المسار سقفاً للمسارات القصيرة.
 * وتحرسه حالةُ `closed-tail` المجمَّدة في `tools/pen_traces.json` — سالباً إلى الأبد.
 */
const HEAD_RATIO = 0.1;
const headSpan = (poly, startTol = TOLERANCE.start) =>
  Math.min(poly.len * HEAD_RATIO, startTol * 2);

// ————— المحاولة: الحكمُ لحظةً بلحظة —————

/**
 * محاولةُ كتابةٍ واحدة على شكلٍ مرجعيّ.
 *
 * الحكمُ **يقع في لحظته لا بعد الفراغ** (علّةُ ق١): `down` تحكم على البداية ساعةَ
 * نزول الإصبع، و`move` تحكم على الاتجاه والانحراف وهو يتحرّك — فيُرشَد الطفل قبل
 * أن ترسخ الحركةُ الخاطئة، لا بعد أن يرفع يدَه عن حرفٍ كتبه مقلوباً.
 *
 * @param {{strokes: Array, dots?: Array}} ref المسارُ المرجعيّ — وهو نفسُه المعروض
 * @param {{tolerance?: number|object, onFault?: Function, onProgress?: Function}} options
 */
export function createTrial(ref, options = {}) {
  const tol = resolveTolerance(options.tolerance ?? ref?.tolerance);
  const parts = partsOf(ref);
  // **الانغلاقُ يُعرَف مرّةً عند بناء المحاولة** وبسماحة المحطة نفسِها (لا بسماحةٍ
  // عامّة): محطةٌ تشدّ سماحتَها تشدّ معها ما تعدّه شكلاً مغلقاً — فلا مقياسان.
  for (const part of parts) {
    part.closed = isClosed(part, tol);
    // **وعتبةُ تغطيته من بيانه**: سماحةُ المحطة لمن لم يُعلِن، ومخفَّفةٌ لمن أعلن
    // (`partCoverage` أعلاه) — تُحسب مرّةً عند البناء فلا مقياسان في محاولةٍ واحدة.
    part.coverage = partCoverage(tol, part.ease);
  }
  const onFault = options.onFault || (() => {});
  const onProgress = options.onProgress || (() => {});

  let index = 0;            // الجزءُ المنتظَر
  let dotHits = 0;
  let taps = 0;            // نقراتُ الطفل — تُعَدّ لتُقابَل بنقاط الحرف          // نقراتُ النقطة المستوفاة من جزء النقطة الحالي
  let attempts = 0;         // كلُّ نزولِ إصبعٍ محاولة
  let faults = [];
  let stroke = null;        // المحاولةُ الجارية
  let metrics = { maxLateral: 0, maxBack: 0, coverage: 0, startDist: 0 };

  function note(code, at, part = index) {
    const target = parts[part];
    const anchor = target ? target.start : at;
    const fault = { code, part, at: [at[0], at[1]], off: [at[0] - anchor[0], at[1] - anchor[1]] };
    faults.push(fault);
    onFault(fault);
    return fault;
  }

  /** نزولُ الإصبع: الشرطُ الأول (البداية) والشرطُ الرابع (الترتيب) يُحسمان هنا. */
  function down(x, y) {
    const p = [x, y];
    attempts++;
    const expected = parts[index];
    if (!expected) {
      stroke = { aim: -1, points: [p], fault: FAULTS.EXTRA };
      return note(FAULTS.EXTRA, p, Math.max(0, parts.length - 1));
    }

    // أقربُ جزءٍ إلى موضع النزول — به يُعرَف **قلبُ الترتيب**: مَن نزل على نقطةٍ
    // وأمامَه جسمٌ لم يُكتب فقد قدّم النقطةَ على الجسم، وهي العادةُ الخاطئة بعينها.
    //
    // **ومن الأجزاء المنتظَرة وحدَها لا المستوفاة** (كشفته أولُ كلمةٍ مركَّبة، الجلسة
    // ٨): الجزءُ المستوفى لا يُكتب ثانيةً فليس وجهاً يُفسَّر به النزول — ولو بقي في
    // العدّ لَلَصِقت نقرةُ النقطة الصحيحةُ بمقعدِ جسمٍ فُرغ منه إلى جوارها (نقطةُ باء
    // «بَابَا» على بُعد ٦٠ من مقعده) فقُرئت **قلبَ ترتيبٍ وهي على ترتيبها**. لم يظهر
    // في الحروف لتباعد أجزائها القليلة، وأجزاءُ الكلمة تتجاور بعشراتها — والشرطُ
    // الرابع كما هو: مَن نزل على جزءٍ **قادمٍ** قبل أوانه تُقرأ له شكواه.
    let best = index;
    let bestGap = Infinity;
    for (const [i, part] of parts.entries()) {
      if (i < index) continue;
      const gap = startDist(part, p);
      if (gap < bestGap) { bestGap = gap; best = i; }
    }

    const gap = startDist(expected, p);
    metrics.startDist = Math.max(metrics.startDist, gap);
    let fault = null;

    if (best !== index && bestGap <= tol.start) {
      const bodyLeft = parts.slice(index).some((part) => part.kind === 'stroke');
      fault = parts[best].kind === 'dot' && bodyLeft ? FAULTS.DOTS_FIRST : FAULTS.ORDER;
    } else if (gap > (expected.kind === 'dot' ? tol.dot : tol.start)) {
      // البدايةُ من الطرف الآخر تُميَّز عن البداية الشاردة: هي الحرفُ يُرسم مقلوباً،
      // وهي أشدُّ ما يُراد تقويمُه («يبدأ الميمَ من أسفل»).
      fault = expected.kind === 'stroke' && dist(p, expected.end) <= tol.start * 1.5
        ? FAULTS.START_END : FAULTS.START_FAR;
    }

    const anchor = expected.kind === 'stroke'
      ? nearestOn(expected.poly, p, 0, headSpan(expected.poly, tol.start)) : { len: 0, d: 0 };
    stroke = {
      aim: index,
      kind: expected.kind,
      points: [p],
      startOk: !fault,
      fault,
      cursor: anchor.len,
      reach: anchor.len,
      entry: anchor.len,   // حيث أرساه نزولُه — وبه تُمنَح رخصةُ الطيّة أو تُمنَع
      wandered: false,
      reversed: false,
      turned: null,        // الطيّةُ التي انعطف فيها القلمُ من صاعدها إلى نازلها
    };
    if (fault) note(fault, p);
    return fault ? { code: fault } : null;
  }

  /** حركةُ الإصبع: الشرطان الثاني (الرتابة) والثالث (الانحراف) يُحسمان هنا. */
  function move(x, y) {
    if (!stroke) return null;
    const p = [x, y];
    stroke.points.push(p);
    if (stroke.kind !== 'stroke' || stroke.aim < 0) return null;

    const poly = parts[stroke.aim].poly;
    // **والنافذةُ الأمامية بمقدار ما مشى القلمُ لا بطول المسار** (كشفه قياسُ الكلمات،
    // الجلسة ٨): علّةُ النافذة أصلاً أنّ **الخطَّ يقترب من نفسه** فيقفز الإسقاطُ إلى
    // شقٍّ بعيدٍ يصادف قربَه — وكانت سعتُها نسبةً من **طول المسار**، فكلَّما طال الخطُّ
    // واقترب من نفسه أكثرَ اتّسعت نافذتُه أكثر، وهو عكسُ ما يلزم. والكلمةُ أطولُ من
    // الحرف وحروفُها متجاورة، **فقِيس أنّ المؤشّر يسبق قلمَ الطفل بخمسمئة وحدةٍ من
    // أوّل ضربة** ثم يُقرأ مضيُّه `wander` برجفة وحدةٍ واحدة («تمر»: القلمُ عند ٦٦٠
    // والمؤشّرُ عند ١١٧٠).
    //
    // **والحدُّ من الحركة نفسِها**: القلمُ يمشي ولا يقفز — فما تقدّم بين نقطتين لا
    // يجاوز ما مشاه بينهما، وله من السماحة ما يحتمل دخولَه وخروجَه عرضياً وارتداده
    // (`lateral × ٢ + back`)، ومن الطيّة ضِعفا سماحة الارتداد ليبلغ مخرجَها. **ولا
    // عتبةَ جديدة**: كلُّها سماحاتُ المحطة نفسُها.
    //
    // **وتُوسَّع بمدى الطيّة المعلَنة وحدَها** (الجلسة ٨، بعد حكم المدير في
    // الانطباقات): الطيّةُ إعلانٌ بأنّ **الطولَ يتقدّم بلا مشي** — القلمُ يصعد ويعود
    // في مكانٍ واحد، فيقطع من الطول ضِعفَ ضلعها وهو لم يبرح موضعَه. فحدُّ الحركة
    // يخنقها إن لم يُوسَّع: قِيس على «تمر» أنّ عيّنةَ الطفل تعبر سنّةً مطويّة
    // فيتخلّف المؤشّرُ عند مبدئها ثم يُقرأ مضيُّه `wander`. **والتوسعةُ مقصورةٌ على
    // مدى المُعلَن** — فما لم يُعلَن يبقى القفزُ فيه ممنوعاً كما كان.
    const step = stroke.points.length > 1
      ? dist(p, stroke.points[stroke.points.length - 2]) : 0;
    const ahead = Math.max(tol.back * 2, step * 3) + tol.lateral * 2;
    // **ولمن دخلها وحدَه**: التوسعةُ رخصةُ الطيّة، ورخصتُها لمن بلغ مبدأها — فمن
    // كان قبلها يبقى على حدّ الحركة، وإلا لَعادت القفزةُ التي حُدّت لأجلها (قِيس:
    // بتوسعةٍ عمياء يسبق المؤشّرُ القلمَ من أوّل الضربة كما كان).
    const ready = foldAhead(parts[stroke.aim].folds, stroke.reach);
    const entered = ready && stroke.reach >= ready.from;
    // **وحبرٌ فُرغ منه ليس وجهاً يُقرأ عليه القلم** (رخصةُ المرور الثاني المعلَن،
    // بند ص٢/ز): أرضيّةُ النافذة `back × ٢` خلفَ المؤشّر لأنّ العودَ اليسيرَ رجفةُ
    // يد. **فإذا أُعلن أنّ هذا الحبرَ يُمشى مرّتين**، فالمرورُ الأول إذا فارقه
    // القلمُ **فُرغ منه** — وحبرُه يعود إليه المسارُ بعدُ في مرورٍ ثانٍ معلَن، فلا
    // حاجةَ به إلى أن يُقرأ عليه القلمُ وهو في نزهته بينهما. ولولا الإعلانُ لَحرُم
    // رفعُ الأرضيّة أصلاً (فما بعد المرور الأول من الحبر يزوره القلمُ حقّاً).
    // **وهو نظيرُ «الأجزاءِ المنتظَرة وحدَها»** في `down`: المستوفى لا يُفسَّر به نزول.
    const walkedPast = parts[stroke.aim].passes
      .reduce((edge, pass) => (stroke.reach > pass.to ? Math.max(edge, pass.to) : edge), 0);
    const lo = Math.max(stroke.cursor - tol.back * 2, walkedPast);
    const hi = Math.max(stroke.cursor + ahead, entered ? ready.to : 0);

    // **الطيّة: الشرطُ الثاني يقيس التقدّمَ ذهاباً وإياباً** (`METHOD.md §٣.١`).
    //
    // ضلعا الطيّة **مكانٌ واحد بطولين**، فنافذةُ الإسقاط وحدَها لا تفرّق بينهما:
    // يدُ طفلٍ ترتجف وهي تصعد يقع إسقاطُها على الضلع النازل — وهو أمامَها بطول
    // الطيّة — ثم يعود إلى الصاعد فيُقرأ **ارتداداً وهو صاعدٌ مصيب**. (أثبتته
    // مراجعةُ المدير: ل/وسطي يسقط برجفة ٤٠، وسنّةُ ب/وسطي المكتوبةُ طبيعياً على خطٍّ
    // واحد تُرفَض `[reverse, wander, short]`.)
    //
    // **فالإعلانُ يرفع اللبس بقسمة الطيّة على القمّة**: ما لم تُبلَغ القمّةُ فالطولُ
    // يُقاس على **الضلع الصاعد**، وبعدها على **النازل**. فيبقى التقدّمُ رتيباً في
    // الوجهين بلا تخفيفٍ في العتبات: **العتباتُ الأربعُ كما هي**، والمتبدّلُ **أين
    // يُلتمَس الإسقاط** — وهي عينُ علّة النافذة أصلاً («لأن الحروف تتقاطع مع نفسها»).
    //
    // **وضلعُ الطور يعطي الطولَ وحدَه، وحبرُ الطيّة واحد**: أما **موضعُ القلم منها**
    // (كم ارتفع، وكم بَعُدَ عن حبرها) فيُقرأ من **أقرب الضلعين** — انظر `inFold` أدناه.
    //
    // **ولا تُمنَح الطيّةُ بلا مشي**: تقييدُ السقف بالقمّة يقع **قبل** بلوغها كذلك،
    // فطفلٌ يدخل من المفرق ويمضي إلى الذراع الخارجة لا يجد ذيلَ الضلع النازل في
    // نافذته فيرث تغطيةَ سنّةٍ لم يكتبها (نظيرُ ثغرة ذيل الشكل المغلق في `headSpan`).
    //
    // **ومتى يُسلَّم من الصاعد إلى النازل؟ حين ينعطف قلمُ الطفل نفسُه** — لا عند رقمٍ
    // يُختار: فإذا بلغ **جوارَ القمّة** (سماحةُ الارتداد نفسُها، فمن قصّر عنها بأقلَّ
    // منها لم يُظلَم) ثم رجع إسقاطُه على الصاعد، فتلك انعطافتُه. ويُقيَّد له بلوغُ
    // القمّة (`reach = apex`) فيُقاس نزولُه منها لا من موضعٍ في الضلع الآخر يصادف
    // قربَه — **وهو ما كان يُقرأ ارتداداً وهو نازلٌ مصيب**. ومن انعطف بعيداً عن
    // القمّة لم يُسلَّم، فسنّةٌ نصفُها ليست سنّة (يردّها الشرطُ الثاني كما كان).
    // **ورخصةُ الطيّة لمن دخلها من مدخلها**: مَن أرساه نزولُه **داخلَ** الطيّة لم يمشِ
    // ضلعَها الصاعد فلا يُقرأ له فيه تقدّم — وهو من جنس `headSpan`: لا يرث أحدٌ ما لم
    // يمشِه، لا تقدّماً ولا رخصة. **وثمنُ تركها**: الطيّةُ مكانٌ واحد، فالصعودُ فيها
    // والنزولُ سواءٌ من أيّ ضلعٍ كانا — ولولا هذا الشرطُ لَقُرئ مسارٌ **معكوسٌ** كلُّه
    // طيّةً مكتوبةً على وجهها متى اتّسعت سماحةُ البداية لطرفَي الشكل (أمسكه ل/وسطي:
    // مداه ٣٢٠ فتبتلعه دائرةُ بدايةٍ مضاعفةٌ ثلاثاً).
    //
    // **وحدُّ القمّة يُحبَس بـ`within`**: نافذةُ `nearestOn` تُرشِّح القطعَ ولا تحبس
    // الطول، فالقطعةُ التي تتخطّى القمّة تُخرِج الإسقاطَ من جهتها — وقد أمسك ذلك
    // **أوّلُ إصبعٍ كتب سنّةً مطويّة في متصفّح**: نزولٌ مصيبٌ على ل/وسطي قُرئ `reverse`
    // لأن الأرضيةَ نُقبت بقطعةٍ واحدة. والحبسُ هنا في حدَّي الطيّة وحدَهما.
    // **ورخصةُ الطيّة تُقاس بمقياس المحرّك لا بالصفر المطلق** (كشفتها عدّةُ المعايرة
    // المجمَّدة يومَ أحكامِ الكرّاسة، ١٢ أغسطس ٢٠٢٦): الرخصةُ لمن دخل الطيّةَ من
    // مدخلها — و**طيّةٌ تبدأ رأسَ المسار مدخلُها الرأسُ نفسُه**، فأيُّ يدٍ حقيقية
    // ترسو على بُعد وحداتٍ منه (`entry` بعد الإرساء) كانت تُحرَم رخصتَها بالمقارنة
    // الصارمة `≤ from` — فتُقرأ سنّةُ الطفل المكتوبةُ على خطٍّ واحد **ارتداداً وهي
    // مصيبة**. (قِيس: ب/وسطي بالعودة على الأثر الرطب ورجفةِ وحدتين ⇐ `reverse` وتغطيةٌ
    // ٣٦٪، وبلا رجفةٍ تُقبَل بانحراف ٤٤ — فالفارقُ رجفتان لا حركة.)
    //
    // **ولا عتبةَ جديدة**: السماحةُ هي `back` بعينها — «ما دون سماحة الارتداد موضعٌ
    // واحد على المسار» بمقياس المحرّك نفسِه (الشرطُ الثاني يستعملها لذلك بعينه)،
    // **والمعنى باقٍ**: مَن أرساه نزولُه **داخل** الطيّة (فوق مدخلها بأكثر من ذلك) لا
    // يرث تقدّمَ ضلعٍ لم يمشِه — ويحرسه `fold-skipped` المجمَّد وحالةُ «أضيقُ
    // المطويّات» في `test_paths.mjs` (المعكوسُ يُرَدّ ولو ضوعفت السماحةُ ثلاثاً).
    // **ولا تُقرأ الطيّةُ قبل أن يبلغها القلم** (كشفه قياسُ الكلمات، الجلسة ٨):
    // قراءتا الطيّة (`inFold`) مقصورتان على ضلعيها — **فهما تتخطّيان نافذةَ الحركة**،
    // وطيّةٌ بعيدةٌ أمامَ القلم تصادف قمّتُها جوارَ موضعه فيقفز المؤشّرُ إليها
    // (قِيس على «سُلَّمْ»: القلمُ عند ٤٩٠ وقمّةُ طيّةٍ على بُعد تسع وحدات عند ٩٣٣،
    // فقفز التقدّمُ أربعمئةً ثم قُرئ مضيُّه `wander`). فتُفعَّل الطيّةُ إذا بلغ
    // جوارَ مبدئها (نافذةُ المحرّك الخلفية `back × ٢` بعينها) — وهو عينُ ما
    // يفعله حدُّ الحركة في سائر المسار.
    const found = foldAhead(parts[stroke.aim].folds, stroke.reach);
    const reached = found && stroke.reach >= found.from - tol.back * 2;
    const fold = reached && stroke.entry <= found.from + tol.back ? found : null;

    /**
     * **القلمُ في حبر الطيّة**: كم ارتفع فيها، ثم أين يقع ذلك من **ضلع الطور**.
     *
     * **وحبرُ الطيّة واحد** (وصفةُ المدير في مراجعة الجلسة ٢ب): فيُقرأ **كسرُ
     * الارتفاع** من **أقرب الضلعين** — إذ **أطبعُ ما تفعله يدُ طفلٍ أن تعود على
     * أثرها الرطب** فتنزل على الضلع الصاعد نفسِه — ثم يُنزَّل ذلك الكسرُ على ضلع
     * الطور: صاعداً من المفرق إلى القمّة، ونازلاً من القمّة إلى المخرج.
     *
     * فيُصان الوجهان معاً بلا مساسٍ بعتبة: **الانحرافُ** بعدُه عن حبر الطيّة لا عن
     * ضلعٍ لم يمشِه (ب/وسطي: فجوةُ ضلعيه ١٦٠ وسماحةُ الانحراف ٩٠ فكان يُردّ `wander`
     * وهو على الحرف تماماً)، **والتقدّمُ** يمضي مع حركته لا يقف عند القمّة (ب/نهائي:
     * كان إسقاطُه على الضلع النازل يقف عند القمّة طولَ نزوله ثم يقفز ويرتدّ، فيُردّ
     * `reverse` وهو نازلٌ مصيب).
     */
    const inFold = (climbing) => {
      const rise = fold.apex - fold.from || 1;
      const drop = fold.to - fold.apex || 1;
      // **وضلعُ الطيّة يُحبَس بحدَّيه** (`within`، الجلسة ٨): نافذةُ `nearestOn` تُرشِّح
      // القطعَ ولا تحبس الطول، **وقطعةٌ تعبر القمّة تُسرِّب الطولَ إلى الضلع الآخر**
      // فيخرج كسرُ الارتفاع مشبَّعاً. والحبسُ هنا من جنس ما تفعله `before` و`after`.
      const up = within(nearestOn(poly, p, fold.from, fold.apex), fold.from, fold.apex);
      const down = within(nearestOn(poly, p, fold.apex, fold.to), fold.apex, fold.to);
      const clamp = (s) => (s < 0 ? 0 : s > 1 ? 1 : s);
      const reads = fold.mirror
        ? [(up.len - fold.from) / rise, (fold.to - down.len) / drop]
        : [climbing ? (up.len - fold.from) / rise : (fold.to - down.len) / drop];
      const seen = reads
        .map((s) => (climbing ? fold.from + clamp(s) * rise : fold.to - clamp(s) * drop))
        // كلتا القراءتين تحتملهما الطيّة، **والفيصلُ اتّصالُ الحركة**: القلمُ يمشي
        // ولا يقفز، فأصدقُ الارتفاعين ما وافق موضعَه قبل لحظة.
        .sort((a, b) => Math.abs(a - stroke.cursor) - Math.abs(b - stroke.cursor));
      return { d: Math.min(up.d, down.d), len: seen[0] };
    };
    // وما قبل الطيّة وما بعدها يبقيان على النافذة كما كانا — والأقربُ منهما ومن
    // الطيّة هو المقروء، فلا يُقرأ ذيلُ الضلع النازل لمن لم يبلغ القمّة (وهو
    // **مَنعُ التغطية بلا مشي**: نظيرُ ثغرة ذيل الشكل المغلق في `headSpan`).
    const nearer = (a, b) => (!a ? b : !b || a.d <= b.d ? a : b);
    const before = () => (lo < fold.from
      ? within(nearestOn(poly, p, lo, fold.from), lo, fold.from) : null);
    const after = () => (hi > fold.to
      ? within(nearestOn(poly, p, fold.to, hi), fold.to, hi) : null);
    const climb = () => nearer(before(), inFold(true));
    const fall = () => nearer(inFold(false), after());

    /**
     * **القلمُ في حبرٍ يُمشى مرّتين**: من أيّ المرورين يُقرأ موضعُه، وعلى أيّهما
     * يُنزَّل؟ — نظيرُ `inFold` أعلاه في بابه، **والفرقُ أنّ الطورين لا يتقابلان**.
     *
     * **والطورُ يُعرَف بما بلغه القلم** لا برقمٍ يُختار: ما لم يبلغ مبدأ المرور
     * الثاني فهو في الأول، وبعده في الثاني. **ثمّ يُقرأ كسرُ الموضع من أقرب
     * المرورين إلى قلمه** — إذ حبرُهما واحد، والأقربُ أصدقُ — **ويُنزَّل على مرور
     * طوره هو**. فيبقى التقدّمُ رتيباً في المرورين بلا تخفيفٍ في العتبات:
     * **العتباتُ الأربعُ كما هي**، والمتبدّلُ **أين يُلتمَس الإسقاط**.
     *
     * **ولا يُنتزَع من نافذة الحركة شيء**: قراءةُ المرور تُعرَض على قراءة النافذة
     * فيؤخذ **أقربُهما إلى الحبر** (`nearer`) — فما لم يكن القلمُ في المرور بقي
     * حكمُه حكمَ سائر المسار، ولا يُقرأ مرورٌ لم يبلغه القلمُ بعد (`passAhead`).
     */
    const twin = passAhead(parts[stroke.aim].passes, stroke.reach);
    // **والرخصةُ لمن هو فيها**: القلمُ بين المرورين **ينزهُ في جزءٍ من الحرف** —
    // فلو قُرئ في نزهته من المرور الآخر لَقفز إليه أو ارتدّ عنه، وهو لم يبلغه بعد
    // ولا فارقه. **فتُقاس على ما بلغه**: مرورٌ يقع مؤشّرُه فيه هو مرورُ طوره، وما
    // خلا منهما فحكمُه حكمُ سائر المسار كما كان (نظيرُ رخصة الطيّة لمن دخل مدخلَها).
    const at = (a, b) => stroke.reach >= a && stroke.reach < b;
    const phase = !twin ? null
      : at(twin.from, twin.to) ? [[twin.from, twin.to], [twin.again, twin.until]]
        : at(twin.again, twin.until + 1) ? [[twin.again, twin.until], [twin.from, twin.to]]
          : null;
    const inPass = ([mine, other]) => {
      const here = within(nearestOn(poly, p, mine[0], mine[1]), mine[0], mine[1]);
      const there = within(nearestOn(poly, p, other[0], other[1]), other[0], other[1]);
      if (!(there.d < here.d)) return here;
      const share = (there.len - other[0]) / ((other[1] - other[0]) || 1);
      return { d: there.d, len: mine[0] + share * (mine[1] - mine[0]) };
    };

    let hit;
    if (!fold) {
      // **وسقفُ المرور الجاري لا يُتخطّى حتى يُمشى** — نظيرُ تقييد الطيّة بقمّتها:
      // مروران في مكانٍ واحد، **وثالثٌ يجاورهما هو الحبرُ الذاهبُ بينهما** (ضلعُ
      // الحلقة يقوم من السطر عند مبدئه)، فيقع بين المرورين مكاناً. فلو تُرك السقفُ
      // مفتوحاً لَقفز المؤشّرُ إليه ورجفةُ الطفل تدنيه منه، **ثمّ قُرئ عودُ القلم
      // إلى مروره ارتداداً وهو ماضٍ فيه** (قِيس على `ط/وسطي`: رجفةُ ٤٥ تُدني القلمَ
      // من ضلع الحلقة على وحدتين وتُبعده عن حبره ٤٤ — فيقفز التقدّمُ مئةً وسبعين).
      const edge = phase ? phase[0][1] : hi;
      hit = nearestOn(poly, p, lo, Math.min(hi, edge));
      // **والحدودُ تُحبَس كما تُحبَس حدودُ الطيّة** (`within` أعلاه): نافذةُ
      // `nearestOn` تُرشِّح القطعَ ولا تحبس الطول، **والقطعةُ التي تعبرها تُسرِّب
      // الإسقاطَ من جهتها** — فيُقرأ القلمُ على حبرٍ فُرغ منه أو لم يبلغه بعد.
      if (walkedPast || phase) hit = within(hit, walkedPast, Math.min(poly.len, edge));
      if (phase) {
        hit = nearer(hit, inPass(phase));
        // **ومتى يُسلَّم من المرور إلى ما بعده؟ حين ينعطف قلمُ الطفل نفسُه** — لا
        // عند رقمٍ يُختار: إذا بلغ **جوارَ آخره** (سماحةُ الارتداد نفسُها، فمن قصّر
        // عنها بأقلَّ منها لم يُظلَم) ثم لم يَمْضِ إسقاطُه، فتلك مفارقتُه. ويُقيَّد
        // له بلوغُ آخر المرور فيُقاس ما بعده من حيث انتهى — وهو عينُ ما يفعله
        // تسليمُ الطيّة عند قمّتها.
        if (stroke.reach >= edge - tol.back && hit.len < stroke.reach) stroke.reach = edge;
      }
    } else if (stroke.turned === fold) {
      hit = fall();
    } else {
      hit = climb();
      // **وبلوغُ القمّة نفسِها انعطافة** (كشفه قياسُ الكلمات، الجلسة ٨): القراءةُ
      // الصاعدة **تتشبّع عند القمّة** ولا تتجاوزها، فمن بلغها بالضبط لا يجد
      // `hit.len < reach` أبداً فيبقى معلَّقاً عندها ولو مضى قلمُه نازلاً، فتُردّ
      // كتابتُه الصحيحة قِصَراً. **ويقع ذلك في يد طفلٍ حقيقية** لا في الاختبار وحدَه:
      // تبسيطُ النقاط (`simplify`) يطرح ما دون ست وحدات، وضلعا الطيّة في الكلمة
      // أقربُ من ذلك — فتسقط عيّنةُ القمّة من مسار الطفل وهو يمرّ عليها. **ولا عتبةَ
      // جديدة**: من بلغ القمّة فليس أمامه إلا النزول فيُسلَّم إليه، ومن قصّر عنها
      // فحكمُه كما كان.
      const atApex = stroke.reach >= fold.apex;
      if ((atApex || hit.len < stroke.reach) && stroke.reach >= fold.apex - tol.back) {
        stroke.turned = fold;
        stroke.reach = fold.apex;
        hit = fall();
      }
    }
    metrics.maxLateral = Math.max(metrics.maxLateral, hit.d);

    /**
     * **صدقُ الاسم على الشكل المغلق** (حمولةُ مراجعة الجلسة ١، تُنفَّذ هنا عند صاحبة
     * الدوائر): طفلٌ يدور دورانَه معكوساً على دائرةٍ كان يُقال له **«يخرج عن المسار»**
     * — والحقُّ **«يعكس اتجاه الحركة»**. وعلّةُ اللبس أنّ الرجوعَ من البداية على شكلٍ
     * مغلق يقع في الطول **قفزةً إلى الأمام** (إلى ذيل المسار) لا ارتداداً، فلا يمسّه
     * الشرطُ الثاني؛ ونافذةُ الإسقاط لا تبلغ الذيلَ فيُقاس بُعدُه عن رأس المسار
     * ويُسمَّى `wander`.
     *
     * **والحكمُ لا يتبدّل — الاسمُ وحدَه**: لا عتبةَ تُمَسّ ولا مقبولَ يصير مردوداً ولا
     * عكسُه. فحين يقع الانحرافُ على شكلٍ **مغلق**، يُسأل سؤالٌ واحد: أهو على الحبر
     * فعلاً (إسقاطٌ على المسار كلِّه داخلَ سماحة الانحراف) **وخلفَ موضعه دائرياً**
     * (أقصرُ الطريقين بينه وبين مؤشّره رجوعٌ يتجاوز سماحة الارتداد)؟ فإن كان فهو راجعٌ
     * على حبره لا خارجٌ عنه — **وذلك ذهبُ لوحة وليّ الأمر** (`METHOD.md §٦`).
     *
     * ولِمَ الشكلُ المغلق وحدَه؟ لأنّ الطولَ فيه وحدَه دائريّ: على مسارٍ مفتوح يبقى
     * الرجوعُ رجوعاً في الطول فيمسكه الشرطُ الثاني باسمه.
     */
    const backwardsOnRing = () => {
      if (!parts[stroke.aim].closed) return false;
      const anywhere = nearestOn(poly, p, 0, poly.len);
      return anywhere.d <= tol.lateral
        && cyclicGap(anywhere.len - stroke.cursor, poly.len) < -tol.back;
    };

    let fault = null;
    if (hit.d > tol.lateral && !stroke.wandered) {
      stroke.wandered = true;
      if (backwardsOnRing()) {
        stroke.reversed = true;      // شكوى واحدة لا صدىً: الاسمُ قيل مرّة
        fault = note(FAULTS.REVERSE, p, stroke.aim);
      } else {
        fault = note(FAULTS.WANDER, p, stroke.aim);
      }
    }
    // **الارتدادُ يُقاس عن أبعد ما بلغ** لا عن آخر نقطة: الرجوعُ خطوةً خطوة عن آخر
    // نقطةٍ لا يتجاوز عتبةً أبداً، فينسلّ عكسُ الاتجاه كلَّه من تحت الشرط.
    const back = stroke.reach - hit.len;
    metrics.maxBack = Math.max(metrics.maxBack, back);
    if (back > tol.back && !stroke.reversed) {
      stroke.reversed = true;
      fault = note(FAULTS.REVERSE, p, stroke.aim) || fault;
    }
    stroke.cursor = hit.len;
    stroke.reach = Math.max(stroke.reach, hit.len);

    const progress = poly.len ? stroke.reach / poly.len : 1;
    metrics.coverage = Math.max(metrics.coverage, progress);
    onProgress({ part: stroke.aim, progress, off: hit.d });
    return fault ? { code: fault.code, progress } : { progress };
  }

  /** رفعُ الإصبع: يستوفي الجزءَ أو يتركه لمحاولةٍ أخرى — بلا حدٍّ ولا عقاب. */
  function up() {
    if (stroke && (stroke.points?.length ?? 0) <= 3) taps++;
    if (!stroke) return null;
    const done = stroke;
    stroke = null;
    if (done.aim < 0) return { ok: false, code: FAULTS.EXTRA, points: done.points };

    const part = parts[done.aim];
    if (part.kind === 'dot') {
      const spread = done.points.reduce((max, p) => Math.max(max, dist(p, done.points[0])), 0);
      const ok = done.startOk && spread <= tol.dot * 0.7;
      if (ok && ++dotHits >= part.count) { dotHits = 0; index++; }
      return { ok, code: done.fault, points: done.points };
    }

    const progress = part.poly.len ? done.reach / part.poly.len : 1;
    let code = done.fault;
    // **وعتبةُ الجزء عتبتُه هو** (`part.coverage`): سماحةُ المحطة إلا أن يُعلِن بيانُه
    // تخفيفاً — والجزءُ الصغير الملحق يُعلِنه (حكمُ المالك، ١٧ أغسطس ٢٠٢٦).
    if (!code && progress < part.coverage) code = note(FAULTS.SHORT, done.points[done.points.length - 1], done.aim).code;
    const ok = done.startOk && !done.wandered && !done.reversed && progress >= part.coverage;
    if (ok) index++;
    return { ok, code, progress, points: done.points };
  }

  return {
    parts,
    tolerance: tol,
    down,
    move,
    up,
    /** الجزءُ المنتظَر الآن — تقرؤه الشاشةُ لتومض نقطتَه وتوجّه سهمَها. */
    get expected() { return parts[index] || null; },
    get index() { return index; },
    get faults() { return faults; },
    get done() { return index >= parts.length; },
    reset() {
      index = 0; dotHits = 0; taps = 0; attempts = 0; faults = []; stroke = null;
      metrics = { maxLateral: 0, maxBack: 0, coverage: 0, startDist: 0 };
    },
    /** حصيلةُ المحاولة — ومنها تأخذ الشاشةُ نجومَها والقياسُ خطأَه المميَّز. */
    verdict() {
      const missing = parts.length - index;
      const all = missing > 0 && !faults.some((f) => f.code === FAULTS.INCOMPLETE)
        ? [...faults, { code: FAULTS.INCOMPLETE, part: index, at: parts[index].start, off: [0, 0] }]
        : faults;
      // **مخالفةُ الطريقة تُرشِد ولا تردّ** (أمرُ المالك، ٢٠ أغسطس ٢٠٢٦: «الحرفُ
      // مقبولٌ ولو كُتب بطريقةٍ غير طريقتنا ولكن شكلُه صحيح… ونقطةُ البداية مساعدةٌ
      // ودليلٌ لا شرط»). **والشكاوى تُسجَّل كلُّها كما كانت** فتقرؤها لوحةُ وليّ
      // الأمر ويومض إليها اللوح — **وإنّما تُنزَع من أسباب الردّ وحدَها**.
      //
      // **والنقصُ يُغتفَر إلا في النقاط**: مَن كتب أجزاءَ الحرف بترتيبٍ غير ترتيبنا
      // يفقد المحرّكُ عدَّها فيُعلَن `incomplete` **وهو أثرُ ترتيبٍ لا نقصُ حرف** —
      // **أمّا نقطةٌ لم تُكتب فحقيقةٌ إملائيةٌ تُردّ** (جدولُ النقاط، `check_paths`).
      //
      // **ومقيسٌ على حصاد الميدان** (٢٠ كتابةً من طفلتين، `field/2026-08-20-*`):
      // موافقةُ عين الإنسان **٧/٢٠ ⇐ ١٣/٢٠**، والردُّ الكاذب **١٢ ⇐ ٦**، والقبولُ
      // الكاذب **١ كما هو**. (ونزعُ النقص بلا استثناء النقاط يعطي ١٢/٢٠ بقبولين
      // كاذبين — **فاستثناءُ النقطة أصوبُ وأقلُّ ثمناً**، وهو مجرَّبٌ لا مظنون.)
      // **وقيدُ الغفران**: يُغتفَر النقصُ لمن **كتب أجزاءً لا تقلّ عن أجزاء الحرف
      // ووفّى نقاطَه** — فذاك كتب الحرفَ كلَّه وإنّما بترتيبٍ غير ترتيبنا. **ومَن
      // كتب أقلَّ فقد نقص حقّاً فيُردّ**: قِيس على الحصاد أنّ «ش/ابتدائي» بجزأين من
      // أربعة تُردّ، و«ي/وسطي» بجزءٍ من ثلاثة تُردّ — **وعينُ الإنسان معهما**.
      const wantDots = parts.reduce((n, part) =>
        n + (part.kind === 'dot' ? (part.count || 1) : 0), 0);
      const wrote = attempts >= parts.length && taps >= wantDots;
      // **وموضعُ النقرة شكلُها لا طريقُها** (حارسُ `test_paths` أمسكه): مَن مادّتُه
      // نقرةٌ — الصفرُ بحكم المالك، وكلُّ نقطةِ حرف — **بُعدُ نزوله عن موضعه تبديلُ
      // شكلٍ لا تبديلُ طريق**، فيبقى ردّاً. **و`dots-first` تبقى إرشاداً**: النقطةُ
      // هناك في موضعها، وإنّما سبقت جسمَها — وذاك زمنٌ لا شكل.
      const seatFault = (f) => (f.code === FAULTS.START_FAR || f.code === FAULTS.START_END)
        && parts[f.part]?.kind === 'dot';
      const blocking = all.filter((f) => (!GUIDE_ONLY.has(f.code) || seatFault(f))
        && !(f.code === FAULTS.INCOMPLETE && wrote));
      return {
        done: index >= parts.length || blocking.length === 0,
        accepted: blocking.length === 0,
        /** **مطابقةُ الطريقة** — كما كان الحكمُ قبل ٢٠ أغسطس: يُقاس ولا يُردّ به. */
        exact: index >= parts.length && all.length === 0,
        /** **قبولُ الشكل**: ما لا يُردّ به وإن أُرشِد إليه — حكمُ المالك أعلاه. */
        guides: [...new Set(all.filter((f) => !blocking.includes(f)).map((f) => f.code))],
        attempts,
        parts: parts.length,
        faults: all,
        codes: [...new Set(all.map((f) => f.code))],
        /**
         * **الخطأُ الأوّل هو الخطأ**: ما بعده صدىً له غالباً — مَن أخطأ بدايةَ جزءٍ
         * بقي الجزءُ منتظَراً، فتُقاس ضربتُه التالية عليه هو فتتوالى الشكاوى. وهذا
         * ما تقرؤه لوحةُ وليّ الأمر (الجلسة ١٠): «يبدأ من أسفل» لا قائمةَ أعراض.
         */
        primary: all[0]?.code || null,
        metrics: { ...metrics },
      };
    },
  };
}

/**
 * **الحَكَمُ الصامت**: يُعيد مسارَ لمسٍ مسجَّلاً على المحرك ويعطي حكمَه — بلا شاشة
 * ولا متصفّح. وهو بابُ عدّة المعايرة (`METHOD.md §٣.٩`): مساراتٌ مسجّلة تُدخَل
 * آلياً ويُثبَت حكمُها حالةً حالة، **سالباً وموجباً**.
 *
 * @param {object} ref المسارُ المرجعيّ
 * @param {Array<Array<[number, number]>>} strokes ضرباتُ الطفل بنقاطها
 */
export function judge(ref, strokes, options = {}) {
  const trial = createTrial(ref, options);
  for (const raw of strokes) {
    const points = simplify(raw);
    if (!points.length) continue;
    trial.down(points[0][0], points[0][1]);
    for (const p of points.slice(1)) trial.move(p[0], p[1]);
    trial.up();
  }
  return trial.verdict();
}

