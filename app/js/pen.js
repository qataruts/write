/** أضيقُ مستطيلٍ يسع نقاطَ ضرباتٍ — صندوقُ حبرٍ أو صندوقُ نموذج. */
export function inkBox(strokes) {
  let x0 = Infinity; let y0 = Infinity; let x1 = -Infinity; let y1 = -Infinity;
  for (const stroke of strokes || []) {
    for (const p of stroke || []) {
      if (p[0] < x0) x0 = p[0];
      if (p[0] > x1) x1 = p[0];
      if (p[1] < y0) y0 = p[1];
      if (p[1] > y1) y1 = p[1];
    }
  }
  return x1 >= x0 ? {
    x0, y0, x1, y1, w: x1 - x0, h: y1 - y0, cx: (x0 + x1) / 2, cy: (y0 + y1) / 2,
  } : null;
}

/** نقاطُ النموذج كلُّها — **أجزاءَ المحرّك نفسَها** (أجساماً ونقاطاً)، فلا صورتان لشكل. */
export const refPoints = (ref) => partsOf(ref)
  .flatMap((part) => (part.kind === 'stroke' ? part.poly.pts : [part.at]));

/**
 * **التوفيق**: إزاحةٌ تُطابق مركزَي الصندوقين، وتحجيمٌ **منتظم** واحد للمحورين.
 *
 * **والمقياسُ وسطٌ هندسيّ لنسبتَي الضلعين** — فلا ينحاز إلى عرضٍ ولا إلى ارتفاع،
 * ونِسَبُ الشكل لا تُشوَّه: كأسٌ أضيقُ يبقى فيها فارقٌ يحتمله كرمُ السماحة، ولا
 * يُمطّ النموذجُ عليها فيصير كلُّ شكلٍ مقبولاً. **وضلعٌ أرقُّ من سماحة الانحراف لا
 * يحمل قياساً** (خطٌّ أفقيّ ارتفاعُه صفر)، فيُقرأ المقياسُ من أخيه وحدَه.
 */
export function fitFree(ref, strokes, tol = TOLERANCE) {
  const child = inkBox(strokes);
  const model = inkBox([refPoints(ref)]);
  if (!child || !model) return null;
  const rx = model.w > tol.lateral ? child.w / model.w : 0;
  const ry = model.h > tol.lateral ? child.h / model.h : 0;
  const s = rx && ry ? Math.sqrt(rx * ry) : (rx || ry || 1);
  /**
   * **والتوفيقُ رأسياً على السطر لا على مركز صندوق الحبر** (`STROKE_ORDER §٨أ.٣`):
   * السطرُ مرسومٌ على اللوح تحت النموذج وتحت يد الطفل معاً، **فهو خطٌّ واحدٌ في
   * الإطارين** — لا يُقاس ولا يُخمَّن. وصندوقُ الحبر يتبدّل بما ليس من الشكل:
   * **أثرُ «ب» عاد بلا نقطته في الميدان فتبدّل مركزُه، فارتفع الانحرافُ من ١٠٧
   * إلى ١٨٦** (`FIELD_TRIAL §٥`) — والسطرُ لا تبدّله نقطةٌ ناقصة.
   * **ومَن لا سطرَ في مادّته** (شكلٌ قديمٌ أو تهيئةٌ) يبقى على مركز صندوقه كما كان.
   */
  /**
   * ————— **مرجعُ التوفيق: جسمُ الشكل لا صندوقُ حبره كلِّه** —————
   *
   * 🔴 **عطبُ الميدان الذي أوجب النظر** (`FIELD_TRIAL §٥` · `STROKE_ORDER §٨أ.٣`):
   * أثرُ «ب» عاد **بلا نقطته**، فصندوقُ الحبر بلا النقطة صندوقٌ آخر — **فتبدّل
   * التوفيقُ فتبدّل الحكم**: انحرافٌ ١٨٦ بدل ١٠٧ ورَدٌّ بدل قبول. **والجزءُ الملحقُ
   * الصغير يزحزح مركزَ الصندوق أكثرَ ممّا يستحقّ**: نقطةٌ واحدة تحت الحرف تُنزل
   * المركزَ سُبعَ الارتفاع، والجسمُ هو الشكل.
   *
   * ⇐ **فيُقاس التوفيق على الأجسام وحدَها**: نقرةٌ ناقصةٌ لا تزحزح مرجعاً، **والنقرُ
   * يبقى محكوماً بشرطه الرابع كما هو** — لم يسقط من الحكم، إنما خرج من **المسطرة**.
   *
   * ⚠ **وأمّا التوفيقُ على السطر** (مقترحُ `STROKE_ORDER §٨ج` لهذا البند) **فقِيس
   * ورُفع للمدير**: يعني أن يُطابَق خطُّ الأساس المرسوم بخطِّ أساس الطفل **افتراضاً
   * أنّه جلس عليه**، وحينئذٍ **يصير الجلوسُ محكوماً** — وهو ما نهى عنه §٨ب بعينه
   * («لا يصير شرطاً خامساً يُردّ به حتى تقيسه ساحةُ الحصاد»). **والقياسُ يوافق
   * النهي**: على آثار الميدان الثلاثة والثلاثين وافق التوفيقُ على السطر **١٧** وحدها
   * ووافق المركزُ والجسمُ **٢٧** — فعشرةُ أطفالٍ كتبوا صحيحاً **فوق السطر أو تحته**
   * كانوا يُردّون `start-far`. **وعلّةُ ذلك في الآثار نفسِها**: كُتبت على لوحٍ **لا
   * سطرَ فيه**، فلا تُدين حكماً يُبنى على لوحٍ فيه سطر. ⇐ **فالسطرُ يُرسم ويُعلَّم
   * اليوم، وتوفيقُه يُقاس في ساحة الحصاد** (ص٣) بآثارٍ كُتبت على السطر.
   */
  const bodyModel = inkBox([partsOf(ref).filter((q) => q.kind === 'stroke')
    .flatMap((q) => q.poly.pts)]);
  // **والنقرةُ تُعرَف بمداها لا بعدد نقاطها**: يدٌ تنقر تترك نقاطاً متتالية في
  // موضعٍ واحد، **فعدُّ النقاط يخدع** — والمقياسُ أنّ **ما لا يبلغ ممرَّ السماحة
  // ليس جسماً**، وهو حدُّ `sizeOf` نفسُه («شكلٌ يغرق في ممرّ سماحته لا يُقاس»).
  const bodyChild = inkBox((strokes || []).filter((q) => {
    const one = inkBox([q]);
    return one && Math.hypot(one.w, one.h) >= tol.lateral;
  }));
  if (!bodyModel || !bodyChild) return { s: s > 0 ? s : 1, child, model };
  const bx = bodyModel.w > tol.lateral ? bodyChild.w / bodyModel.w : 0;
  const by = bodyModel.h > tol.lateral ? bodyChild.h / bodyModel.h : 0;
  const bs = bx && by ? Math.sqrt(bx * by) : (bx || by || 1);
  return { s: bs > 0 ? bs : 1, child: bodyChild, model: bodyModel };
}

/** نقلُ نقطةٍ من إطار الطفل إلى إطار النموذج — عكسُ التوفيق، وهو هو. */
const toModel = (fit, p) => [
  fit.model.cx + (p[0] - fit.child.cx) / fit.s,
  fit.model.cy + (p[1] - fit.child.cy) / fit.s,
];

/**
 * **الحجمُ المعقول — وحدُّه محسوبٌ من الصندوق لا مكتوبٌ بيد**:
 *   · **أصغرُ ما يُقبَل** أن يزيد قطرُ حبره على **ممرّ السماحة** (`lateral × ٢`):
 *     شكلٌ يغرق في ممرّ سماحته لا يُقاس أصلاً — أيُّ خربشةٍ فيه تُقرأ حرفاً.
 *   · **وأكبرُ ما يُقبَل** أن يسعه **صندوقُ المادّة** وممرُّ سماحته من كلّ جهة.
 * وكلاهما جملةٌ تُقال («اكْتُبْهُ أَكْبَرْ») لا ردٌّ صامت.
 */
export function sizeOf(ref, strokes, tol = TOLERANCE) {
  const child = inkBox(strokes);
  if (!child) return null;
  const corridor = tol.lateral * 2;
  if (Math.hypot(child.w, child.h) < corridor) return SIZE.SMALL;
  /**
   * **وأكبرُ ما يُقبَل يُقاس بحبر النموذج لا بالخليّة** (بند ص٢/ب ٢، تصحيحُ يومه):
   * منذ صار الشكلُ يجلس على **سطرٍ واحدٍ للهجاء كلِّه** صارت خليّتُه خليّةَ السطر —
   * تسع أعلى الهجاء وأنزلَه معاً (٢٫٤٧ ألفاً)، **فلا تمسك دالاً كُتبت بحجم اللام
   * ولا نوناً مضاعفةً مرّتين ونصفاً**. **والنموذجُ هو المقياس**: يُقاس إليه كما
   * تُقاس إليه الأربعةُ الأخرى. ومَن لا حبرَ لنموذجه فخليّتُه حدُّه كما كان.
   *
   * **وحدُّه كرمُ السماحة نفسُه** (`FREE.ease`) وممرُّه: الخطوةُ الحرّة تكرم سماحاتِها
   * بهذا العامل، **فما جاوزه حجماً جاوز ما تكرمه المحطةُ أصلاً** — ولا رقمَ يُختار.
   * وقياسُه على العدّة المجمَّدة: نونٌ أوسعُ بأربعين في المئة **تُقبَل**، ومضاعفةٌ
   * مرّتين ونصفاً **يُقال لها «اكْتُبْهُ أَصْغَرْ»**.
   */
  const model = inkBox([refPoints(ref)]);
  const [bw, bh] = model ? [model.w * FREE.ease, model.h * FREE.ease] : boxOf(ref);
  return child.w > bw + corridor || child.h > bh + corridor ? SIZE.BIG : null;
}

/** سماحةُ المحطة مكرَّمةً — الأبعادُ كلُّها بعاملٍ واحد، والتغطيةُ نسبةٌ فلا تُمَسّ. */
export const easeTolerance = (tol, factor = FREE.ease) => ({
  start: tol.start * factor,
  lateral: tol.lateral * factor,
  back: tol.back * factor,
  dot: tol.dot * factor,
  coverage: tol.coverage,
});

/**
 * **الحَكَمُ الثاني** — نظيرُ `judge` للخطوة الحرّة: يقيس الحجمَ أوّلاً (فيُرشِد إن
 * شذّ)، ثم يوفّق النموذجَ على صندوق الحبر، ثم **يستدعي الشروطَ الأربعة بأعيانها**
 * على الموفَّق. فلا حَكَمان ولا شرطٌ خامس: هو هو، والمتبدّلُ **إطارُ القياس**.
 */
export function judgeFree(ref, strokes, options = {}) {
  const tol = resolveTolerance(options.tolerance ?? ref?.tolerance);
  const size = sizeOf(ref, strokes, tol);
  if (size) {
    return {
      done: false,
      accepted: false,
      size,
      attempts: strokes.length,
      parts: partsOf(ref).length,
      faults: [],
      codes: [],
      primary: null,
      metrics: { maxLateral: 0, maxBack: 0, coverage: 0, startDist: 0 },
    };
  }
  const fit = fitFree(ref, strokes, tol);
  const mapped = fit ? strokes.map((stroke) => stroke.map((p) => toModel(fit, p))) : strokes;
  const verdict = judge(ref, mapped, { ...options, tolerance: easeTolerance(tol) });
  return { ...verdict, size: null, scale: fit ? fit.s : 1 };
}

