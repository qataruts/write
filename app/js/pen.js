//
// المادّةُ المدرَّسة **حركةُ القلم**: بدايتُها واتجاهُها وترتيبُ أجزائها — لا الشكلُ
// النهائي. فالحكمُ هنا على الحركة لا على التغطية، و«تتبّعُ نقاطٍ» يقبل أيَّ لمسٍ
