/**
 * سماحةُ محطةٍ بعينها: عاملٌ عدديّ يشدّ المسافات كلَّها (`0.8` أشدّ من `1`)، أو
 * كائنٌ يبدّل ما يشاء منها بعينه. والتغطيةُ نسبةٌ فلا يمسّها العامل.
 */
/**
 * **وسماحةُ المادّة تسافر معها — فمن لم يُعطِ سماحةً أخذ سماحتَها** (بند ص٢/ب ١):
 * الكلمةُ كانت تحمل مقياسَ حروفها فيها (`ref.tolerance`) **وتنتظر شاشةً تمرّره**،
 * فإن حكم عليها حاكمٌ بلا خيار حُكم بسماحة حرفٍ يملأ شبكتَه وهي أصغرُ منه.
 * **وصار الحرفُ مثلَها** يومَ جلس على السطر بنسبته: `د` تأخذ من الخليّة سُبعَ ما
 * تأخذه `ك`. **فالمادّةُ أوْلى بسماحتها من الافتراض**، والمحطةُ إن نصّت غلبت.
 */
export function resolveTolerance(value) {
  if (typeof value === 'number' && value > 0) {
    return {
      start: TOLERANCE.start * value,
      lateral: TOLERANCE.lateral * value,
      back: TOLERANCE.back * value,
      dot: TOLERANCE.dot * value,
      coverage: TOLERANCE.coverage,
    };
  }
  return { ...TOLERANCE, ...(value || {}) };
}

