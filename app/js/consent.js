/**
 * 🔴 **إذنُ تقييم الكلمات بالإنترنت** — بابٌ واحدٌ يعرف الجوابَ في التطبيق كلِّه.
 *
 * **سندُه أمرُ المالك** (٢٥ أغسطس ٢٠٢٦): «ننبّه المستخدم أنّ التطبيق يستخدم
 * الإنترنت لتقييم الكتابة، **نطلب قبولَه عند أول مرّة يفتح التطبيق**».
 *
 * **والعهدُ يُنقض في الكلمات وحدَها وبعلمٍ صريح**: عهدُ العائلة الأصلُ «مساراتُ
 * كتابة الطفل لا تغادر جهازه أبداً» يبقى **على الحروف كاملاً** — وهي التي يُقاس
 * بها الحكمُ ويُعايَر عليها. أمّا الكلماتُ فتُقرأ بخدمةٍ سحابية بإذن وليّ الأمر.
 *
 * **والافتراضُ لا** (`ask`): لا يُنادى شيءٌ حتى يقول وليُّ الأمر «نعم» صراحةً —
 * ومَن قال «لا» أو كان بلا إنترنت مضى الطفلُ كما كان (مرسومُ المضيّ ٢٣ أغسطس).
 */

const KEY = 'uktub.reader.consent.v1';

/** ما اختاره وليُّ الأمر: `yes` أو `no` أو `ask` (لم يُسأل بعد). */
export function consentState() {
  try {
    const got = localStorage.getItem(KEY);
    return got === 'yes' || got === 'no' ? got : 'ask';
  } catch {
    return 'ask';                      // خزنٌ ممنوع ⇒ لا إذن ⇒ لا شبكة
  }
}

export function setConsent(value) {
  try {
    localStorage.setItem(KEY, value === 'yes' ? 'yes' : 'no');
  } catch { /* لا خزنَ ⇒ يبقى الجوابُ «لا» بحكم الافتراض */ }
}

/** **الشرطُ الجامع**: أيُقرأ الآن؟ — إذنٌ صريحٌ وشبكةٌ حاضرة، وإلا فلا. */
export function readingAllowed() {
  if (consentState() !== 'yes') return false;
  return !(typeof navigator !== 'undefined' && navigator.onLine === false);
}

/** نصُّ البيان — واحدٌ في التطبيق كلِّه: في بطاقة أول تشغيل وفي لوحة وليّ الأمر. */
