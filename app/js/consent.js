  + ' (نقاطٌ فقط — لا صورة ولا صوت ولا اسم) لتُقرأ الكلمةُ فتُعرف دقّةُ الكتابة.'
  + ' أمّا الحروفُ فتُقاس داخل الجهاز ولا تغادره أبداً.';
