//
// **وحدةٌ مفصولةٌ عن كل ملفٍّ يمرّ به قلمُ الطفل — عمداً وبنيوياً**، ودرسُها من
// ميدان اقرأ يومَ وُلدت هناك: حارسُ الخصوصية (`test_pen.mjs §١`) يمنع أيَّ
// `https://` في **حاملي مسار الطفل**، و«بلِّغنا» تحمل روابطَ خارجية **بطبعها**.
// فلو جمعهما ملفٌّ واحد، لَما بقي إلا أن يُثقَب الحارسُ باستثناء — والاستثناءُ في
// حارس خصوصيةٍ بابٌ يتّسع. **فلا يجمعهما ملفٌ أبداً**: الروابطُ تسكن هنا وحدَها،
// ويبقى سطحُ اللوح صفرَ عناوين. **حصانةٌ بنيوية لا استثناءَ حارس** — ويثبت
// الفصلَ `tools/test_feedback.mjs` بجردٍ من القرص لا بقائمةٍ مكتوبة.
//
// **ولا تعرف هذا الوحدةُ من الطفل شيئاً**: لا تستورد `progress.js` أصلاً، فليس
// لها إلى نجومه ولا اسمه ولا رحلته سبيلٌ **تقنيّاً لا تأدّباً**. وسياقُ الرسالة
// ثلاثةٌ كلُّها من الجهاز لا من الطفل: **اسمُ التطبيق ونسخةُ قشرته وموضعُ الشاشة**.
//
// ولا يعرف الشبكةَ كذلك: رابطا `<a>` **يُفتحان بنقرة الراشد ولا يُجلَبان** — صفرُ
// طلباتٍ من التطبيق نفسِه، والمرسِل يرى نصَّه كاملاً في تطبيقه قبل أن يُرسل.

import { h } from './ui.js';

/** رقمُ العائلة وبريدُها المرجع — من لوحة وليّ الأمر وحدَها (`FAMILY.md`). */
const WHATSAPP = '97433882806';
const MAILBOX = 'info@mishkat.qa';

/** عنوانُ الرسالة — واحدٌ في القناتين فلا يفترق نصّان. */
const SUBJECT = 'بلاغ من تطبيق اُكْتُبْ';

/**
 * **«بلِّغنا»**: بابُ الجمهور لكل خطأٍ أو مقترح — من قسم وليّ الأمر وحدَه (فعلُ
 * راشدٍ متعمَّد، ولا زرَّ في شاشة طفل)، رابطا واتساب وبريدٍ **مملوءان بسطر سياقٍ**
 * يجعل البلاغ قابلاً للعمل: **نسخةُ القشرة وموضعُ الشاشة**.
 *
 * **ونسخةُ القشرة من القشرة الحيّة** لا من ثابتٍ يشيخ هنا (سابقةُ `parent.js`
 * وبلاغُ العائلة `version-visibility`): تُسأل بـ`postMessage` فتردّ `VERSION` من
 * عندها — **فالمبلَّغُ نسخةُ ما يعمل على هذا الجهاز**، وبها وحدَها يُعرف أنّ الشكوى
 * على شيفرةٍ وصلت. وقبل أن يصل الجوابُ يمضي السطرُ بلا نسخة: **بلاغٌ ناقصُ السياق
 * خيرٌ من زرٍّ لا يُنقر**.
 *
 * **وموضعُ الشاشة عنوانُ التوجيه لا موضعُ الطفل من رحلته**: الأولُ من المتصفّح
 * (`#/parent` وأخواتُه — أسماءُ محطاتٍ يشترك فيها كلُّ طفل)، والثاني تقدُّمُه هو —
 * **وهو المحظور**.
 */
export function feedbackSection() {
  let shell = '';                       // نسخةُ القشرة حين تصل — وقبلها فارغة

  const context = () => `${SUBJECT}${shell ? ` (قشرة ${shell})` : ''}`
    + ` — الموضع ${location.hash || '#/'}:\n`;

  const wa = h('a', { class: 'btn', target: '_blank', rel: 'noopener' }, 'عبر واتساب');
  const mail = h('a', { class: 'btn' }, 'عبر البريد');

  const arm = () => {
    const text = context() + 'اكتب ملاحظتك هنا — وأرفق لقطة شاشة إن أمكن.';
    wa.href = `https://wa.me/${WHATSAPP}?text=${encodeURIComponent(text)}`;
    mail.href = `mailto:${MAILBOX}?subject=${encodeURIComponent(SUBJECT)}`
      + `&body=${encodeURIComponent(text)}`;
  };
  arm();

  // جوابُ القشرة يدخل السياق متى وصل — ويُسأل صراحةً فلا تنتظر الوحدةُ سؤالَ غيرها
  navigator.serviceWorker?.addEventListener?.('message', (e) => {
    if (e.data?.type === 'version' && wa.isConnected) { shell = e.data.version; arm(); }
  });
  navigator.serviceWorker?.controller?.postMessage({ type: 'version' });

  return h('div', {},
    h('p', { class: 'hint' },
      'وجدتَ خطأً؟ عندك اقتراح؟ رسالتُك تصلنا مباشرة — وتُفتح في تطبيقك فترى نصَّها '
      + 'قبل إرسالها، ولا يُرفَق معها شيءٌ من بيانات طفلك.'),
    h('div', { class: 'row' }, wa, mail),
  );
}
