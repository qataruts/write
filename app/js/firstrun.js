// **بطاقةُ أوّل تشغيل** — «ثبّت أوّلاً ثم امتحن» (بلاغ العائلة
// `2026-08-17-install-before-exam-first-run-card.md`، وبندُ «جلسة ط» في `SESSIONS.md`).
//
// ————— العطبُ الذي وُلدت منه، وهو مقيسٌ لا متوهَّم —————
//
// بوابةُ العائلة تدعو الوالدَ: «اختبر مستوى طفلك — لا يبدأ من الصفر». فيفتح التطبيقَ
// **في المتصفّح** ويمتحن ابنَه — **وعلى الآيباد والآيفون للتطبيق المثبَّت مخزنٌ مستقلٌّ
// عن سفاري** — ثم يثبّته فيجد الرحلةَ من أوّلها: **قياسٌ صحيحٌ ضاع بسبب بابٍ خاطئ**.
// (ذاقه المالكُ بنفسه ١٧ أغسطس ٢٠٢٦: فتح سفاري فوجد رحلةَ طفلته من الصفر.)
//
// **والعلاجُ في موضع العيب**: مَن دخل التطبيقَ أوّلَ مرّةٍ يُدَلّ على البابين **قبل أن
// يمشي** — لا أن نعتمد على أن يقرأ صفحةً قبل أن يدخل. فالترتيبُ «ثبّت ثم امتحن»
// يُنفَّذ **بنيةً لا نصيحة**: في المتصفّح غير المثبَّت **لا تُعرَض دعوةُ اللحاق أصلاً**،
// بل دعوةُ التثبيت وحدَها.
//
// ————— أربعةُ قيودٍ تحكم هذه الوحدة —————
//
// ١) **على رحلةٍ بكرٍ وحدَها** (`progress.untouched()`: صفرُ نجومٍ وصفرُ محاولاتٍ في
//    ليتنر) — فطفلٌ يمشي منذ أسبوع لا يراها أبداً. **وتسقط بأوّل نجمةٍ يكسبها** من
//    نفسها: الشرطُ يُقرأ في كل رسمةٍ للخريطة، ولا حالَ ثانيةٌ تُخزَّن لتشيخ.
// ٢) **و«لاحقاً» تُخفيها إلى الأبد** — بمفتاحٍ في `localStorage` لا يعود.
// ٣) **وزرُّها يفتح لوحةَ وليّ الأمر لا الامتحانَ مباشرة** (`#/parent` وأمامها مسألةُ
//    الضرب) — فلا يفتحه طفلٌ على نفسه، وهو عينُ القيد ١ لبوابة اللحاق: **لا بابَ لها
//    من شاشة طفل**. ولذلك **لا تعرف هذه الوحدةُ `catchup.js` ولا عنوانَه**: تقف عند
//    باب اللوحة، واللوحةُ تدلّ على قسمها — ويجرد ذلك `test_catchup.mjs` من القرص.
// ٤) **ولا وسمَ على الطفل**: البطاقةُ خطابُ بالغٍ بلفظه وبشارته («لوليّ الأمر»)،
//    **ولا كلمةَ «امتحان» على شاشة الطفل** — فالزرُّ يحمل اسمَ الميزة كما تسمّيه
//    اللوحةُ نفسُها («بوابةُ اللحاق»)، لا وصفَ حالِ الطفل ولا امتحاناً يُعلَن عليه.
//
// **وصفرُ صوت**: بطاقةُ بالغٍ تُقرأ، لا شاشةُ طفلٍ تُنطَق — ولا نصَّ يدخل
// `audio_queue.json`. **ولا فراغَ محجوز** حين تغيب: لا تُبنى أصلاً.
//
// 🔒 **ولا تعرف الشبكة**: قرارٌ وعرضٌ محليان صرفان، كأختها `install.js`.

import * as progress from './progress.js';
import { installed } from './install.js';
import { h, go, BRAND } from './ui.js';

// **مخزنُنا لا مخزنُ اقرأ** (كسابقة `install.js`): سابقةُ `STORE_KEY` في `progress.js`،
// ويحرس الفاحصُ تطابقَهما قراءةً من القرص.
const KEY = 'uktub.firstrun.v1';

/**
 * **قرارُ العرض — دالّةٌ نقيّة تُفحَص بجدول حالاتٍ كامل** (نظيرُ `installState`):
 * ماذا تُري هذه البطاقةُ الآن؟
 *
 * **واسمُ حالها `placement` لا اسمُ وحدة الامتحان**: هذه الوحدةُ لا تعرفها ولا تعرف
 * عنوانَها (القيد ٣) — والاسمُ هنا وصفُ **الدعوة** لا نداءُ شاشة.
 *
 * @returns {'hidden'|'install'|'placement'}
 */
export function firstRunState({ untouched, installed: isInstalled, dismissed, preview }) {
  if (preview) return 'hidden';   // مقيّمٌ يتصفّح: بطاقةٌ فوق شريط المعاينة ضجيج
  if (dismissed) return 'hidden'; // «لاحقاً» — إلى الأبد
  if (!untouched) return 'hidden'; // مشى في الرحلة: الدعوةُ فاتت موضعَها
  // **جوهرُ البلاغ**: في المتصفّح تُقدَّم دعوةُ التثبيت وحدَها — فما يُقاس هنا لا ينتقل
  return isInstalled ? 'placement' : 'install';
}

const memo = () => { try { return JSON.parse(localStorage.getItem(KEY)) || {}; } catch { return {}; } };
const remember = (patch) => {
  try { localStorage.setItem(KEY, JSON.stringify({ ...memo(), ...patch })); } catch { /* تخزينٌ ممتلئ: تظهر البطاقةُ ثانيةً، ولا تضرّ */ }
};

/** الحالُ الحيّة — كلُّ مدخلٍ من مالكه: البكارةُ من `progress`، والتثبيتُ من `install`. */
function state() {
  return firstRunState({
    untouched: progress.untouched(),
    installed: installed(),
    dismissed: Boolean(memo().dismissedAt),
    preview: progress.PREVIEW,
  });
}

/**
 * البطاقةُ إن كان لها موضع، وإلا `null` — **ولا فراغَ محجوز**.
 * @param {() => void} rerender إعادةُ رسم الخريطة بعد «لاحقاً» (فتسقط في مكانها)
 */
export function firstRunCard(rerender) {
  const mode = state();
  if (mode === 'hidden') return null;

  const later = h('button', {
    class: 'btn btn--ghost firstrun-later',
    onclick: () => { remember({ dismissedAt: Date.now() }); rerender(); },
  }, 'لاحقاً');

  // **والدعوتان لا تجتمعان أبداً**: هذا هو الترتيبُ المنفَّذ بنيةً — دعوةُ التثبيت
  // وحدَها في المتصفّح، ودعوةُ اللحاق وحدَها في المثبَّت.
  const body = mode === 'placement'
    ? [
      h('p', { class: 'firstrun-text' },
        'إن كان طفلك يعرف بعضَ ما في الرحلة أصلاً — من مدرسةٍ أو مركز — فلا يبدأ من'
        + ' الصفر: افتح لوحةَ وليّ الأمر، ومن «بوابةِ اللحاق» يكتب بيده عيّنةً من كل'
        + ' وحدة، فيُفتح له ما أثبته ويقف حيث ينكسر.'),
      h('div', { class: 'firstrun-row' },
        h('button', {
          class: 'btn btn--primary firstrun-go',
          // **إلى بوابة اللوحة لا إلى الامتحان** (القيد ٣): مسألةُ الضرب أمامها،
          // ثم يدلّ الوالدَ **قسمُها** في اللوحة.
          onclick: () => go('#/parent'),
        }, 'بوابةُ اللحاق'),
        later),
    ]
    : [
      h('p', { class: 'firstrun-text' },
        `ثبّت «${BRAND}» على الجهاز أوّلاً، ثم ابدأ منه: تقدّمُ طفلك يُحفَظ داخل`
        + ' التطبيق المثبَّت، وما يُكتب في المتصفّح لا ينتقل إليه من نفسه.'),
      // **الصيانةُ الصادقة** (البند ٤): مَن وقع فيه يُذكَر له طريقُ النقل الوحيد —
      // **حيث يحتاجه** لا في الوثائق وحدَها. والطريقُ قائمٌ في اللوحة اليومَ
      // (حفظُ ملفٍّ واستعادتُه)، فلا يُوعَد بما ليس عندنا.
      h('p', { class: 'firstrun-note' },
        'وإن كان قد بدأ في المتصفّح فعلاً: احفظ «نسخةً احتياطية من تقدّمه» من لوحة'
        + ' وليّ الأمر هنا، ثم استعِد الملفَّ في التطبيق بعد تثبيته — فهو طريقُ النقل'
        + ' الوحيد بين المخزنين.'),
      h('div', { class: 'firstrun-row' }, later),
    ];

  return h('section', { class: `firstrun firstrun--${mode}`, 'aria-label': 'بطاقةٌ لوليّ الأمر' },
    h('span', { class: 'firstrun-who' }, 'لوليّ الأمر'),
    ...body,
  );
}
