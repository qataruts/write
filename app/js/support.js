/** هل وضعُ الدعم كلُّه مشتغل؟ (المفتاح الأعلى — وهو مطفأٌ ابتداءً). */
export const modeOn = () => state.on === true;

/**
 * هل هذا المقبض مشتغل؟ — **المقابض تتبع المفتاح الأعلى** ابتداءً: يشغّل وليُّ الأمر
 * الوضعَ فتعمل كلُّها، ثم يطفئ ما لا يحتاجه طفلُه (فالتشغيل قرارٌ واحد لا خمسة).
 */
export const isOn = (key) => modeOn() && key in KNOBS && state[key] !== false;

// ————— «مسطرةُ الامتحان الواحدة» (بلاغ `2026-08-17-support-and-placement-coexist.md`) —————
//
// **قاعدةُ المالك**: العونُ الذي **يريح** يُسمح في امتحان اللحاق، والذي **يجيب** يُمنع.
// فداخل الامتحان تُعطَّل مقابضُ `measures` قطعاً (الجرعةُ والسماحةُ الموسَّعة) وتسري
// مقابضُ الراحة (نموذجٌ أبطأ وخطٌّ أغلظ وهدوءٌ حسّيّ) — فيُقاس الطفلُ بمسطرةٍ واحدة
// ولا يُمتحَن بشاشةٍ تُربكه، ولا يُفتَح له بسماحةٍ أوسع ما لم يُفتَح لغيره.
//
// **ونطاقُه مدّةُ البناء لا عَلَمٌ يُخزَّن**: `duringExam` تلفّ نداءً **متزامناً**
// وتردّ الحالَ في `finally` — فلا يبقى الامتحانُ مشتغلاً بعد مغادرة الطفل شاشتَه،
// ولا يعبر إعادةَ تحميل (العَلَمُ المخزَّن يعلق مفتوحاً — عيبُ حالةٍ صامت).
//
// **وهو الطبقةُ الثانية لا الأولى**: الأولى بنيويّة — `catchup.js` و`review.js`
// لا تستوردان `easeFor` ولا `mayEase` أصلاً، يجردها الحارسُ على المصدر.
let examDepth = 0;

/** هل نحن الآنَ داخل بناءِ تمرينِ امتحانِ لحاق؟ */
export const examOn = () => examDepth > 0;

/** يُجري `fn` بمسطرة الامتحان الواحدة ويردّ الحالَ ولو رمى (نداءٌ متزامن). */
export function duringExam(fn) {
  examDepth++;
  try {
    return fn();
  } finally {
    examDepth--;
  }
}

/** هل يعمل هذا المقبضُ الآن؟ — وما مسَّ القياسَ لا يعمل داخل الامتحان ولو شُغِّل. */
const active = (key) => isOn(key) && !(examOn() && KNOBS[key].measures);

/** مقدارُ هذا المقبض الآن — `standing` ما دام مطفأً، و`supported` إن اشتغل. */
export const value = (key) => (active(key) ? KNOBS[key].supported : KNOBS[key].standing);

