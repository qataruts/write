/**
 * **السماحةُ الموسَّعة في الاكتساب وحدَه** (بندُ العقد ٥ — حكمُ الدراسة: التعلّمُ بلا
 * خطأ مصمَّمٌ لمرحلة الاكتساب، و«لا عونَ للجواب» قاعدةُ الطلاقة، Haring 1978:
 * اكتساب ← طلاقة ← تعميم ← تكييف). فالتوسيعُ لا يجوز إلا في **أوّل لقاءٍ بمهارةٍ
 * جديدة**: صندوقُ ليتنر صفر — وما ارتفع صندوقُه فقد جاوز الاكتساب فيُكتب بالمسطرة
 * القائمة.
 *
 * **وهي إذنٌ لا فعل**: من يستدعيه شاشاتُ الاكتساب الأربع (`lesson.js` · `copy.js` ·
 * `fade.js` · `sentence.js`)، **ولا تستدعيه المراجعةُ ولا البوابةُ ولا اللحاق
 * ألبتّة** — وحصانتُها بنيوية: تلك الوحداتُ لا تعرف هذه الدالّة أصلاً، يجردها
 * `tools/test_support.mjs` على المصدر. **وطبقةٌ ثانية في الامتحان**: `ease` من
 * `measures` فيعود إلى `standing` داخل `duringExam` ولو استدعاه مستدعٍ يوماً.
 *
 * (ومحطةُ التهيئة خارجَه بعلّتها: لا مهارةَ لها في ليتنر ولا صندوق — أشكالٌ تُمشى
 * ولا تُقاس، فلا «أوّلَ لقاءٍ» يُحدّ به الإذن. ولها مقابضُ الراحة كسائر الشاشات.)
 */
export const mayEase = (box = 0) => active('ease') && box === 0;

/**
 * **سماحةُ هذه المحاولة ووسمُ عونها من قرارٍ واحد** — فلا يفترق ما وُسِّع عمّا وُسِم:
 * تردّ السماحةَ كما تُمرَّر إلى `pen.js` (رقمُ المحطة كما هو إن لم يُؤذَن، ومضروباً
 * في المعامل إن أُذن) ومعها `aided` التي تمضي إلى `progress.recordAttempt`.
 *
 * **وسماحةُ المحطة تبقى مصدرَها**: ما لا يعلن سماحةً يبقى بلا سماحةٍ معلنة (`undefined`
 * ⇒ ثوابتُ `pen.js` نفسُها) — فالمطفأُ لا فرقَ فيه ببايت.
 *
 * @param {number|object|undefined} tol سماحةُ المحطة كما تُعلنها مادّتُها
 * @param {number} box صندوقُ ليتنر لهذه المهارة (صفرٌ = أوّلُ لقاء)
 */
export function easeFor(tol, box = 0) {
  if (!mayEase(box)) return { tolerance: tol, aided: false };
  const base = typeof tol === 'number' && tol > 0 ? tol : 1;
  return { tolerance: base * value('ease'), aided: true };
}

